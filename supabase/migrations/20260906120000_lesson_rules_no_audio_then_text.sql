-- Новое правило: после голосового сообщения (audio) следующая нода не
-- должна быть текстовой (text) — смена формата после голоса должна идти
-- через фото, а не через текст.
--
-- Проверено на конфликт: не пересекается ни с одним из существующих
-- правил. Ближайшее по теме — «после демонстрации фразы в таблице
-- обязателен перевод, в script или отдельной репликой следом» — то
-- правило про table (там своя озвучка через script), не про audio, прямого
-- пересечения нет.
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'После голосового сообщения (audio) следующая нода не должна быть текстовой (text) — если нужно сменить формат подачи сразу после голоса, используй фото, а не текст. У audio уже есть видимая расшифровка-подпись под сообщением: сразу следующий текст выглядит как повтор того же способа подачи («снова читать»), а не как смена формата. Фото после голоса — настоящая смена модальности (слушал → смотрит).',
  45,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'После голосового сообщения (audio) следующая нода не должна быть текстовой%'
);
