-- Разбор реального прогона пользователя выявил несколько классов ошибок,
-- которые точечные правки одного узла не ловят — нужны как пункты финального
-- чек-листа по всему уроку:
--   1) правило «перевод — белый курсив» чинилось по одному найденному
--      случаю за раз, вместо сквозной проверки всех «...» с кириллицей —
--      десяток старых узлов остались неисправленными;
--   2) у одной table (ручной режим) не было ни одного distractors — список
--      слов вне таблицы состоял ровно из нужных слов, гадать было нечего;
--   3) распознавание ответа по фото с неразличимой деталью (напиток в
--      кружке) не должно предлагать другой вариант той же детали как
--      отвлекающее слово — угадать невозможно ни так, ни так;
--   4) replyToSeq указывал на reaction-ноду (у неё нет текста) — цитата в
--      чате рендерилась пустой, виден был только «Вы:»/имя без содержимого.
--
-- Проверено на конфликт: не пересекается ни с одним из существующих правил.
insert into public.lesson_rules (rule_text, sort_order, category)
select v.rule_text, v.sort_order, 'checklist'
from (values
  ('Проверь ВСЕ "«...»" с кириллицей по всему уроку (не только то, что только что писал) — это перевод, красится белым (#fdfcfc) курсивом ЦЕЛИКОМ включая сами кавычки-ёлочки, без bold/underline. Частая ошибка: правишь один найденный случай и не проверяешь остальные — правило нарушается по всему уроку одинаково, чини все сразу через поиск по тексту, а не по памяти.', 202),
  ('Каждая table (ручной режим) с непустым answer должна иметь хотя бы один distractors — без него список слов вне таблицы состоит РОВНО из нужных слов, гадать нечего, задание перестаёт быть упражнением на выбор.', 203),
  ('Если answer/words зависит от детали, которую НЕЛЬЗЯ увидеть на приложенном фото (напиток в кружке, конкретный вид еды/предмета через стекло и т.п.) — distractors НЕ должны включать другой вариант той же неразличимой детали (другой напиток и т.п.): ученик не может выбрать между чаем и кофе по одной фотографии кружки, а угадывать смысла нет. Замени такой отвлекатель на явно постороннее слово.', 204),
  ('replyToSeq должен указывать на ноду, у которой ЕСТЬ читаемое содержимое (текст/собранная фраза), — никогда на reaction/system: у них нет текста для цитаты, и цитата в чате отрендерится пустой (виден только «Вы:»/имя без текста). После КАЖДОЙ правки графа (сплайс, новые ноды, сигналы) пересчитывай реальный seq (см. computeSeqMap в nodeGraph.js) для каждого узла с replyToSeq — старое число могло стать нерабочим, даже если сам узел не менялся.', 205)
) as v(rule_text, sort_order)
where not exists (
  select 1 from public.lesson_rules where rule_text = v.rule_text
);
