-- fill_blanks («Составь предложение») теперь ВСЕГДА отправляет собранную
-- фразу в чат — поле sendAnswerToChat и галочка в редакторе убраны из кода
-- (PlayerPanels.jsx/NodeFillBlanksPicker.jsx/NodeAnswerFields.jsx): без этого
-- предложение исчезало без следа после сборки, а реплаю «В ответ на» не на
-- что было ссылаться. Легенда должна знать об этом, чтобы не предлагать
-- дублировать фразу в responseCorrect.
--
-- Проверено на конфликт: первое упоминание обязательной отправки для
-- fill_blanks.
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'У fill_blanks («Составь предложение») собранная фраза ВСЕГДА уходит в чат отдельным пузырём справа — верная сразу, неверная последней (третьей) попыткой. В отличие от table/phrase_assembly, тут это НЕ настраивается галочкой (поля sendAnswerToChat у fill_blanks больше нет) — иначе после сборки предложение просто исчезает без следа, и цитату «В ответ на» не на что ставить. responseCorrect/responseWrong при этом НЕ должны повторять собранную фразу словами — фраза уже видна в чате как отдельный пузырь, см. принцип про эхо-повтор.',
  190,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'У fill_blanks («Составь предложение») собранная фраза ВСЕГДА уходит в чат%'
);
