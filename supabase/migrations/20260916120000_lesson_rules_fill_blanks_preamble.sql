-- Новое правило: перед КАЖДОЙ нодой fill_blanks («Составь предложение»)
-- обязательна короткая текстовая нода-пояснение прямо перед ней — простыми
-- словами, какая форма/что именно проверяется. Без такого пояснения ученик
-- видит фразу с дырками без контекста: непонятно, какое правило проверяется
-- и почему тут вообще есть дырка.
--
-- Проверено на конфликт: не пересекается ни с одним из существующих правил
-- (первое правило, упоминающее fill_blanks в тексте).
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'Перед КАЖДОЙ нодой fill_blanks («Составь предложение») обязательна короткая текстовая нода-пояснение прямо перед ней — простыми словами, какая форма/что именно проверяется (например «Проверим настоящее время» или «А теперь — прошедшее»). Тон разговорный, не техническое ТЗ («заполни пропуск буквой», «выбери верную форму» — плохо; «Как звучит настоящее время? Заполни» — хорошо). Без такого пояснения ученик видит фразу с дырками без контекста: непонятно, какое именно правило проверяется и почему тут вообще есть дырка.',
  183,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'Перед КАЖДОЙ нодой fill_blanks%'
);
