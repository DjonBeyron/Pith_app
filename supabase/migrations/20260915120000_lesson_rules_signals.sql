-- Новое правило: сигналы ошибок (signals) у table (ручной режим) и
-- phrase_assembly — персональная подсказка на конкретный слот ответа вместо
-- общего responseWrong. Когда использовать: только там, где у ошибки есть
-- ДВЕ РАЗНЫЕ типичные причины, которые стоит различить отдельной репликой
-- (например «неверное местоимение» и «неверная форма глагола») — не на
-- каждый слот подряд просто потому что поле существует, иначе общий
-- responseWrong работает не хуже.
--
-- Проверено на конфликт: не пересекается ни с одним из существующих правил
-- (первое упоминание signals в списке).
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'table (ручной режим) и phrase_assembly умеют signals — персональную подсказку на конкретный слот ответа (ноду-спутник, которая проигрывается поверх панели при первой ошибке именно в этом месте, попытка не тратится). Ставь signals там, где у ошибки есть ДВЕ разные типичные причины (например «неверное местоимение» и «неверная форма глагола») — так подсказка называет причину, а не просто повторяет общее «неверно». Без чёткого разделения причин один общий responseWrong работает не хуже — не заводи signals на каждый слот подряд просто потому что поле существует.',
  175,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'table (ручной режим) и phrase_assembly умеют signals%'
);
