-- Событие журнала feed_ladder — итог «лесенки» из 5 слайдов на втором визите (features/feed/ladder).
-- props: steps — строка «сложность:мс:трудно» по слайдам через запятую (например «1:9100:0,2:1500:1»),
-- top — наибольшая сложность, пройденная без трудностей и с просмотром от 8 с (0 — нет),
-- hard — самая лёгкая сложность, на которой были признаки трудности выше top (0 — нет).
-- Без имени в белом списке log_events тихо отбросит событие. Идемпотентна: повторный запуск ничего не меняет.
insert into public.app_event_names (name, note)
values ('feed_ladder', 'итог лесенки второго визита (steps, top, hard)')
on conflict (name) do nothing;
