-- Колода повтора: не больше половины карточек со звуком или голосом. Кнопка
-- «Не могу слушать» убирает такие карточки до конца сессии, и слово не должно
-- остаться без карточек. Правка правила lesson_rules про колоду повтора
-- (вставлено миграцией 20260925130000). Идемпотентно: заменяется точная
-- прежняя фраза; повторный запуск (или правка правила вручную) ничего не меняет.
update public.lesson_rules
set rule_text = replace(
  rule_text,
  'Хотя бы одна карточка — на слух (фраза приходит только голосом).',
  'Хотя бы одна карточка — на слух (фраза приходит только голосом), но карточек со звуком или голосом — не больше половины колоды (минимум 50% — без звука): ученик может нажать «Не могу слушать», и тогда для него останутся только карточки без звука.'
)
where rule_text like 'Урок-слово (между Стартом и Финалом) отдаёт в JSON колоду повтора%';
