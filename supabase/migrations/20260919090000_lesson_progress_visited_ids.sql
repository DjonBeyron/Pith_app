-- Список id пройденных нод к моменту чекпойнта — чтобы «Продолжить урок»
-- мог восстановить историю чата ВЫШЕ точки входа (раньше лента при резюме
-- начиналась пустой: чекпойнт хранил только последнюю ноду и процент).
-- Порядок — как реально шёл показ (с учётом повторов при «ошибся →
-- подсказка → снова вопрос», см. graphPlayerVisits.js/appendVisit), не
-- пересчитанная задним числом «главная линия» урока — так история
-- совпадает с тем, что студент реально видел.
alter table public.lesson_progress
  add column if not exists visited_ids jsonb not null default '[]'::jsonb;
