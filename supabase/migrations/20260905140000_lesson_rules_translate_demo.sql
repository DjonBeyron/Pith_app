-- Новое правило: если таблица демонстрирует конкретную фразу-пример целиком
-- (не общее правило, а саму фразу — «I try every day»), после совместной
-- сборки обязателен перевод, но не подстрочником.
--
-- Проверено на конфликт с уже существующими 17 правилами: единственная
-- смежная тема — принцип «после верного ответа ученика реакции обычно
-- достаточно, повторять перевод избыточно» (это про ОТВЕТ ученика, который
-- уже виден в чате). Новое правило — про ДЕМОНСТРАЦИЮ учителя ДО ответа
-- ученика, там перевод ещё не звучал вообще. Чтобы это не читалось как
-- противоречие, разграничение явно прописано в самом тексте правила.
--
-- Идемпотентно: вставка только если такого правила ещё нет (по устойчивому
-- куску текста, а не по id — таблица не хранит внешних id для строк).
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'Если таблица (обычно dictator) демонстрирует КОНКРЕТНУЮ фразу-пример целиком — не общее правило, а саму фразу («I try every day», «She tries hard») — сразу после того как фраза собрана вместе с учеником, обязательно должен прозвучать её перевод. Неважно, где именно: внутри самого script («I try every day — я пытаюсь каждый день», как уже принято в этом формате) или отдельной репликой сразу следом — но фраза-пример не должна оставаться без перевода вовсе. Перевод — живая реплика, а не подстрочник и не «Перевод: ...»: как сказал бы учитель в переписке. ✗ «Перевод: я пытаюсь каждый день» ✓ «Вот и получилось — я пытаюсь каждый день». Это про ДЕМОНСТРАЦИЮ учителя до того, как ученик сам отвечает — не путать с переводом уже верного ОТВЕТА ученика, который обычно избыточен (см. принцип про реакцию на верный ответ).',
  135,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'Если таблица (обычно dictator) демонстрирует КОНКРЕТНУЮ фразу-пример%'
);
