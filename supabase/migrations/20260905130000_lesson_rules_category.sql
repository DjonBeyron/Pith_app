-- Правила формирования урока делятся на два разных по смыслу типа (см.
-- PROJECT.md, «Легенда: правила формирования урока — из кода в БД»):
--   · principle — проверяется В МОМЕНТ написания конкретной ноды
--     («на table в режиме dictator обязателен script»);
--   · checklist — проверяется ТОЛЬКО по готовому черновику, целиком по
--     всему уроку («перед сдачей — сверь каждый ответ на повторы»).
-- Раньше оба типа лежали одним плоским списком, и второй тип чаще всего
-- терялся: для него нет момента, когда он обязан сработать сам. Разделение
-- позволяет экспортировать их как два разных раздела легенды: правила —
-- читать по ходу дела, чек-лист — выполнить целиком перед тем как отдать
-- урок.

alter table public.lesson_rules
  add column if not exists category text not null default 'principle'
    check (category in ('principle', 'checklist'));

-- Из 17 исходных принципов четыре по смыслу — чек-лист «перед сдачей», а не
-- правило «здесь и сейчас». Помечаем их по устойчивому куску текста (id из
-- миграции-посева тут не поможет — она не задавала свои id).
update public.lesson_rules set category = 'checklist'
where category = 'principle' and (
  rule_text like '%Перед сдачей урока — явно выпиши%'
  or rule_text like '%сверь каждый Русский промпт%'
  or rule_text like '%должно быть хотя бы одно задание НА СЛУХ%'
  or rule_text like '%утверждение о ПУТИ%'
);
