-- Этап 3 системы повторения «Моё обучение» (PROJECT.md → «Колоды»): у урока-
-- слова своя колода карточек повтора (lessons.script.reviewCards, в обменном
-- JSON — поле reviewCards). Правило для автора/модели, собирающей урок:
-- как выглядит хорошая карточка. Идемпотентно: вставка только если такого
-- правила ещё нет.
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'Урок-слово (между Стартом и Финалом) отдаёт в JSON колоду повтора reviewCards: [{ nodes: [...] }], минимум 3 карточки. Карточка — «пересланный кусочек чата» из 1–3 нод: ровно ОДНО задание (word_choice, phrase_assembly, fill_blanks, photo_choice, table) и при необходимости 1–2 ноды контекста перед ним. Карточку показывают через дни после урока, отдельно от него и вперемешку с другими словами — поэтому она понятна сама по себе, без остального урока (никаких «как мы только что видели», replyToSeq только внутри карточки). Карточки проверяют то же слово, что урок, но НЕ копируют задания урока дословно: другой контекст, другое предложение, другой порядок вариантов — иначе ученик вспоминает ответ, а не слово. Хотя бы одна карточка — на слух (фраза приходит только голосом). ref внутри карточки свои (n1, n2 …), переходы и signals — только на ноды той же карточки.',
  210,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'Урок-слово (между Стартом и Финалом) отдаёт в JSON колоду повтора%'
);
