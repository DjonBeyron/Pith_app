-- Уточнение правила про фото и время действия (миграция
-- 20260906130000_lesson_rules_photo_time_question.sql, применена только
-- что в этой же сессии): «явный вопрос, указывающий на время» оказался
-- неверным механизмом — подпись-вопрос не годится, потому что ответ и так
-- собирается из данных слов, а не отвечает на отдельный вопрос про время.
--
-- Верный механизм: подпись — короткая история от третьего лица, в которой
-- ГЛАГОЛ УЖЕ СТОИТ в нужном времени по обычной русской грамматике
-- («пытается» — настоящее, «пробовал» — прошедшее, «будет пробовать» —
-- будущее) — ученик считывает время из естественного предложения, а не из
-- вопроса или абстрактного слова-подсказки. Фото при этом иллюстрирует
-- сцену действия.
--
-- Обновляем ТУ ЖЕ строку (по устойчивому куску старого текста), а не
-- добавляем новую — это правка, а не отдельный принцип.
update public.lesson_rules
set rule_text = 'Если фото само по себе не может однозначно передать время действия (прошедшее/настоящее/будущее/повторяющееся — застывший кадр этого не показывает), подпись должна быть КОРОТКОЙ ИСТОРИЕЙ от третьего лица, где сам глагол уже стоит в нужном времени по обычной русской грамматике — «пытается» (настоящее), «пробовал» (прошедшее), «будет пробовать» (будущее). Ученик считывает время из естественного предложения, как из любой обычной фразы, а не разгадывает вопрос или абстрактное слово-подсказку («Уже было», «Когда это было?» — оба варианта хуже: первый двусмысленный, второй заставляет отвечать на вопрос про время отдельно от самого упражнения). ✗ «Уже было» / «Когда это было?» ✓ «Пробовал прокатиться ⛸️» / «Каждый раз пытается закрыться 🚪» / «Завтра будет пробовать бегать 🏃». Фото при этом иллюстрирует сцену действия — историю, а не наоборот.',
    updated_at = now()
where rule_text like 'Если фото само по себе не может однозначно передать время действия%'
  and rule_text like '%ЯВНЫМ ВОПРОСОМ%';
