-- Два новых правила по прямой просьбе пользователя: раскладка урока была
-- слишком плотной ("всё очень плотно"), а сигнальные ноды могли лечь поверх
-- других нод без чёткого места на холсте.
--
-- 1) Общий ориентир по «воздуху» между нодами на холсте (шаг не меньше
--    ~500-560 по x внутри ряда, ~450-500 между рядами веток).
-- 2) Система размещения нод-сигналов: свой ряд ниже родителя, x по номеру
--    слота — чтобы сигнальные ноды никогда не ложились поверх других.
--
-- Проверено на конфликт: оба текста уникальны, не пересекаются с уже
-- существующими правилами (в т.ч. с правилом про зазор в 4 ширины ноды
-- между смысловыми блоками — то правило про ГРАНИЦЫ зон, это — про обычный
-- шаг между соседними нодами и про отдельный случай сигнальных нод).
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'Не экономь место на холсте при раскладке (pos) нод — плотная сетка технически работает, но мешает читать граф и провоцирует коллизии при дальнейших правках. Ориентир: шаг между соседними нодами внутри одной ветки/ряда — не меньше ~500-560 по x (сама нода ~308 шириной — так остаётся заметный просвет, а не впритык), между рядами разных веток по вертикали — не меньше ~450-500. Граница между смысловыми блоками/зонами — кратно больше обычного шага (см. правило про 4 ширины ноды). Если раскладка получилась плотнее — раздвинь программно (например масштабируй все pos на общий коэффициент >1 относительно начала координат — так гарантированно не появится новых коллизий, ни одна пара нод не может сблизиться от равномерного растяжения).',
