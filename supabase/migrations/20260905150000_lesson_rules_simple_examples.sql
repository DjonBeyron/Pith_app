-- Новое правило: дополнения в примерах должны быть грамматически простыми —
-- не вводить вскользь тему (артикли и т.п.), которая не является предметом
-- урока.
--
-- Проверено на конфликт с уже существующими правилами: прямых пересечений
-- нет. Ближе всего «Один урок = одно целевое слово» (принцип уже про
-- фокус на одной теме) — новое правило его усиливает, а не дублирует: то
-- правило про сам целевой ГЛАГОЛ, это — про грамматику ВОКРУГ него в
-- примерах-дополнениях.
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'Дополнения и примеры в упражнениях должны быть грамматически простыми — не вводи вскользь тему, которая не является предметом урока. «He tries the guitar» новичку неясно, зачем артикль «the»: это отдельная большая тема, никак не связанная с формами глагола — он либо запомнит фразу бездумно, либо отвлечётся на непонятное вместо разбираемой темы. Предпочитай неисчисляемые существительные без артикля («tries coffee», «tries yoga») или множественное число («try new recipes»), а не «tries the guitar» / «tried the puzzle» / «will try the bike». Если артикль в примере неизбежен — это сигнал заменить сам пример, а не объяснять артикль мимоходом.',
  15,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'Дополнения и примеры в упражнениях должны быть грамматически простыми%'
);
