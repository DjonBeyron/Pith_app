-- Разбор прогона пользователя выявил ещё два класса ошибок:
--   1) У ~60 нод урока не было базового приглушённого highlight (opacity
--      0.75, белый) на весь текст — они рендерились ЯРКО-белым (#e8e8ea,
--      полная непрозрачность), в отличие от остального урока, где
--      неакцентированный текст выглядит серым. Особенно часто пропускали у
--      коротких служебных нод (сигналы ошибок, заголовки зон, однословные
--      реплики) — казалось, что там «нечего выделять».
--   2) replyToSeq структурно валиден (указывает на существующую ноду с
--      текстом, не на reaction/system), но СМЫСЛОВО указывает не туда —
--      на совсем другое, более раннее упражнение. Причина: seq
--      пересчитывается по графу при каждом импорте, и старое число молча
--      устаревает при любой правке графа выше по цепочке. Найдено и
--      исправлено 3 таких случая в реальном уроке (n43, n59, n63 — см.
--      PROJECT.md), которые предыдущая (чисто структурная) проверка не
--      ловила.
--
-- Проверено на конфликт: первый пункт — новый принцип (первое упоминание
-- обязательной базовой подложки); апдейт replyToSeq-правила целится в
-- старую формулировку без нового маркера "СМЫСЛОВО".
insert into public.lesson_rules (rule_text, sort_order, category)
select
  'У КАЖДОЙ ноды с текстом (content/text/caption) должен быть базовый highlight на ВЕСЬ текст: {mode:"text", color:"#ffffff", opacity:0.75} — единый приглушённый тон переписки, на фоне которого выделяются акценты (bold/цвет/курсив/подчёркивание). Без него любой не покрытый акцентом кусок текста рендерится ЯРКО (реальный цвет по умолчанию — #e8e8ea, непрозрачно), то есть «кричит» наравне с акцентами, хотя не должен. Добавляй эту базовую подложку СРАЗУ при создании ноды, даже если в ней пока нет ни одного акцента — особенно легко забыть у коротких служебных нод: сигналы ошибок, системные заголовки зон (Часть 1/2/3), короткие переходные реплики, одно слово или один эмодзи.',
  189,
  'principle'
where not exists (
  select 1 from public.lesson_rules
  where rule_text like 'У КАЖДОЙ ноды с текстом (content/text/caption) должен быть базовый highlight%'
);

update public.lesson_rules
set rule_text = 'replyToSeq должен указывать на ноду, у которой ЕСТЬ читаемое содержимое (текст/собранная фраза), — никогда на reaction/system: у них нет текста для цитаты, и цитата в чате отрендерится пустой (виден только «Вы:»/имя без текста). После КАЖДОЙ правки графа (сплайс, новые ноды, сигналы) пересчитывай реальный seq (см. computeSeqMap в nodeGraph.js) для каждого узла с replyToSeq — старое число могло стать нерабочим, даже если сам узел не менялся. Мало проверить, что seq структурно существует и не указывает на reaction/system — нужно ещё прочитать содержимое цели и убедиться, что оно СМЫСЛОВО относится к тому, что говорит цитирующая нода (обычно это соседняя по графу нода на расстоянии в 1-3 шага). Симптом такого бага: цитата ссылается на ответ/фразу из СОВСЕМ ДРУГОГО, более раннего упражнения, никак не связанного с текущей репликой.'
where rule_text like 'replyToSeq должен указывать на ноду%'
  and rule_text not like '%СМЫСЛОВО%';

