-- Проверка public.next_remind_at (миграция 20261027120000_remind_time.sql, A3).
-- Как запускать: вставить файл целиком в Supabase → SQL Editor, предварительно
-- применив миграцию. Данные не пишет и не читает — только считает функцию, поэтому
-- безопасно и на боевой базе. Любой провал — ошибка «assertion failed: …» с
-- названием случая; тишина и «Success» — всё прошло.
-- Ожидаемые значения посчитаны независимо (Python zoneinfo), а не самой функцией.

do $$
declare
  v timestamptz;
begin
  -- Москва (без перехода на летнее время), 7:40 = 04:40 UTC
  v := public.next_remind_at('Europe/Moscow', '07:40', '2026-10-27 03:00+00');
  assert v = '2026-10-27 04:40+00', 'Москва 7:40: до времени — сегодня, got ' || v;
  v := public.next_remind_at('Europe/Moscow', '07:40', '2026-10-27 05:00+00');
  assert v = '2026-10-28 04:40+00', 'Москва 7:40: после времени — завтра, got ' || v;
  v := public.next_remind_at('Europe/Moscow', '07:40', '2026-10-27 04:40+00');
  assert v = '2026-10-28 04:40+00', 'Москва 7:40: ровно в момент — строго после, got ' || v;

  -- Нью-Йорк, 20:00, весенний переход 2026-03-08 (зима UTC−5 → лето UTC−4)
  v := public.next_remind_at('America/New_York', '20:00', '2026-03-07 21:00+00');
  assert v = '2026-03-08 01:00+00', 'NY весна: накануне перехода, got ' || v;
  v := public.next_remind_at('America/New_York', '20:00', '2026-03-08 02:00+00');
  assert v = '2026-03-09 00:00+00', 'NY весна: после перехода всё ещё 20:00 местных (23 ч, не 24), got ' || v;

  -- Нью-Йорк, 20:00, осенний переход 2026-11-01 (лето UTC−4 → зима UTC−5)
  v := public.next_remind_at('America/New_York', '20:00', '2026-10-31 23:00+00');
  assert v = '2026-11-01 00:00+00', 'NY осень: накануне перехода, got ' || v;
  v := public.next_remind_at('America/New_York', '20:00', '2026-11-01 01:00+00');
  assert v = '2026-11-02 01:00+00', 'NY осень: после перехода всё ещё 20:00 местных (25 ч, не 24), got ' || v;

  -- Смена пояса Москва → Токио: тот же «20:00», другой момент
  v := public.next_remind_at('Europe/Moscow', '20:00', '2026-10-27 12:00+00');
  assert v = '2026-10-27 17:00+00', 'Москва 20:00, got ' || v;
  v := public.next_remind_at('Asia/Tokyo', '20:00', '2026-10-27 12:00+00');
  assert v = '2026-10-28 11:00+00', 'Токио 20:00 (там уже 21:00 — значит завтра), got ' || v;

  -- Пояс или время не известны — null
  assert public.next_remind_at(null, '20:00', '2026-10-27 12:00+00') is null,
    'tz null → null';
  assert public.next_remind_at('Asia/Tokyo', null, '2026-10-27 12:00+00') is null,
    'время null → null';

  -- Результат всегда в будущем относительно p_from (не дальше суток + 1 ч перехода)
  v := public.next_remind_at('Pacific/Auckland', '00:00', '2026-10-27 12:00+00');
  assert v > '2026-10-27 12:00+00' and v <= '2026-10-27 12:00+00'::timestamptz + interval '25 hours',
    'Окленд 0:00: в пределах суток, got ' || v;
end $$;
