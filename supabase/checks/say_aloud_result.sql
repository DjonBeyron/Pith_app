-- Ручная проверка public.say_aloud_result (миграция 20261027200000_say_aloud_result.sql, этап E).
-- АВТОМАТИЧЕСКИ НЕ ПРОГОНЯЛАСЬ: у разработки нет Postgres, функция проверена только чтением.
-- Функция пишет в память и XP ТЕКУЩЕГО пользователя (auth.uid()), поэтому блоков
-- «do $$ … assert … $$» здесь нет: они менялись бы чужие данные. Проверка — сценарий + select.
--
-- Как проверять: на ТЕСТОВОЙ базе, под тестовым аккаунтом (в SQL Editor — выполнить
-- `select set_config('request.jwt.claim.sub', '<uuid тестового пользователя>', false);`
-- перед вызовами, либо дернуть RPC из приложения / REST под токеном тестового аккаунта).
-- В памяти тестового пользователя нужны слова: A (due_on <= сегодня), B (due_on через 10 дней),
-- C (due_on = завтра). Подготовить: админка → «Память» → «＋ В обучение» / «Прожить день».
--
-- Сценарий и ожидания (A, B, C — ключи слов; «нет» — слова нет в памяти):
--  1. say_aloud_result('[{"word":"A","ok":true}]')                → xp = 1, moved = 0;
--     due_on и step слова A не изменились.
--  2. Повтор того же вызова в тот же день                          → xp = 0 (слово уже оплачено сегодня).
--  3. say_aloud_result('[{"word":"B","ok":true}]')                → xp = 0 (B не «к повтору»), память не тронута.
--  4. say_aloud_result('[{"word":"B","ok":false}]')               → moved = 1; due_on слова B = сегодня + 1, step прежний.
--  5. say_aloud_result('[{"word":"C","ok":false}]')               → moved = 0 (срок уже завтра, не отодвигается).
--  6. say_aloud_result('[{"word":"нет","ok":false},{"word":"нет","ok":true}]') → xp = 0, moved = 0, без ошибки.
--  7. Слово дважды в одном раунде ({"word":"A","ok":true},{"word":"A","ok":false}) → считается промахом:
--     A сдвигается на завтра, XP за него нет.
--  8. Потолок: 11+ разных слов «к повтору» с ok=true за день (по раундам) → суммарно xp за день = 10, дальше 0;
--     xp_today в ответе не превышает xp_cap = 10.
--  9. Не массив / больше 20 элементов: say_aloud_result('{}') и массив из 21 элемента → { ok: false, reason: 'items' }.
-- 10. Без входа (anon): функция недоступна (revoke ... from anon, public) — ошибка прав.
-- 11. Серия: user_profiles.current_streak и дата последнего дня серии после любых вызовов не меняются.
--
-- Просмотр результата (подставить uuid тестового пользователя):

select day, xp, rounds, words
from public.say_aloud_days
where user_id = '00000000-0000-0000-0000-000000000000'   -- uuid тестового пользователя
order by day desc
limit 7;

select word, step, due_on
from public.word_memory
where user_id = '00000000-0000-0000-0000-000000000000'
order by due_on, word;

select xp, current_streak
from public.user_profiles
where id = '00000000-0000-0000-0000-000000000000';
