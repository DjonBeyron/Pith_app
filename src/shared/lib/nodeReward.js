// Включена ли у ноды награда (⭐ XP). Правило одно на весь проект: галочка
// в редакторе холста и раздача XP в плеере обязаны видеть одно и то же —
// иначе автор снимает галочку, а XP всё равно делится на эту ноду.
//
// Обычные типы-ответов: награда по умолчанию ВКЛЮЧЕНА (reward !== false) —
// ученик там реально отвечает.
//
// Таблица в режиме «Авто» — исключение: она собирается сама под диктовку,
// ученик ничего не решает, поэтому награда по умолчанию ВЫКЛЮЧЕНА. Это
// именно дефолт, а не запрет: поставил автор галочку — награда работает
// как у всех остальных.
export function isRewardOn(type, data) {
  if (type === 'table' && (data?.mode ?? 'dictator') === 'dictator') {
    return data?.reward === true
  }
  return data?.reward !== false
}
