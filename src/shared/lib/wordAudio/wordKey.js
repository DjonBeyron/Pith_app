// Ключ слова в библиотеке озвучки (word_audio.key). Одно и то же слово в
// уроках пишется по-разному — «He», «he», «he,», «he.» — а озвучка у него
// одна, поэтому в базу кладём нормализованную форму, а модули ищут по ней же.
//
// Озвучиваем ТОЛЬКО чистую латиницу: строка с кириллицей (перевод в ячейке
// таблицы, смешанное «cake — торт») не озвучивается вовсе, а не «по
// английской части» — так решено с пользователем. Апострофы остаются в
// ключе (don't ≠ dont), дефисы тоже (well-known). Чип из нескольких слов
// («New York», «going to») — одна запись, ключ = вся строка.
//
// ЗЕРКАЛО В SQL: public.word_key (миграция 20260924120000_word_memory.sql) —
// тем же ключом сервер заносит слово в память повторения (word_memory).
// Меняешь правила здесь — меняй и там, иначе клиент не найдёт память слова.

// Знаки препинания по краям — не часть слова
const EDGE_PUNCT = /^[\s.,!?;:"'“”«»()[\]{}…\-–—]+|[\s.,!?;:"“”«»()[\]{}…\-–—]+$/g

// Что разрешено внутри ключа: латинские буквы, цифры, пробел, апостроф, дефис
const ALLOWED = /^[a-z0-9' -]+$/

// Убирает пунктуацию по краям, схлопывает пробелы, приводит апострофы к
// одному виду. Регистр НЕ меняет — это форма для показа в меню
export function cleanWordText(text) {
  return String(text ?? '')
    .replace(/[’‘`´]/g, "'")
    .replace(EDGE_PUNCT, '')
    .replace(/\s+/g, ' ')
    .trim()
}

// null — слово не для озвучки (пусто, есть кириллица/иные символы, нет ни
// одной латинской буквы)
export function wordKey(text) {
  const clean = cleanWordText(text).toLowerCase()
  if (!clean || !ALLOWED.test(clean) || !/[a-z]/.test(clean)) return null
  return clean
}
