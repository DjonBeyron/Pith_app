// Склейка одинаковых запросов на старте: ShellV2 монтирует все вкладки сразу, и
// лента, «Память» и «Профиль» одновременно просят один и тот же список
// (модули, гонка) — лишние копии делили с первым кадром ленты канал.
// Пока запрос в полёте И начался не раньше maxAgeMs назад, повторные вызовы
// получают тот же promise; завершился (успех или ошибка) — следующий вызов
// идёт заново, ничего не кэшируется. Окно maxAgeMs страхует от устаревшего
// ответа: вызвавший сразу после записи не получит запрос, начатый до неё.
// fn — функция без аргументов. Вызывающий сам копирует результат, если будет
// его менять (общий объект отдаётся всем).
export function shareInFlight(fn, maxAgeMs = 1500, now = () => Date.now()) {
  let cur = null
  return () => {
    if (cur && now() - cur.t < maxAgeMs) return cur.p
    const entry = { t: now(), p: null }
    entry.p = fn()
    cur = entry
    const clear = () => { if (cur === entry) cur = null }
    entry.p.then(clear, clear)
    return entry.p
  }
}
