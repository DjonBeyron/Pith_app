// Настройки слов пользователя в сценах (шаг 5): константы, а не app_settings — миграций нет.
// Позже превращается в настройку так: ключ `scene_vars` в app_settings (публичное чтение, как feed_signals),
// загрузка при старте приложения, а isSceneVarsEnabled() читает значение оттуда (сейчас — константа).

// Аварийный выключатель: false — везде показывается ЗАПАСНОЕ слово шаблона, память не читается
export const SCENE_VARS_ENABLED = true
// Сколько ждём слова пользователя перед стартом сцены, мс (потом запасное слово, и сцена уже не меняется)
export const SCENE_VARS_WAIT_MS = 500
// Сколько ещё можно ждать озвучку выбранных слов (word_audio) из этого же бюджета: нет — слово без озвучки, реплика синтезом
export const SCENE_VARS_AUDIO_WAIT_MS = 250

export const isSceneVarsEnabled = () => SCENE_VARS_ENABLED
