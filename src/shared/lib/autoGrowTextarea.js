// Растягивает textarea по высоте так, чтобы весь текст был виден без
// внутреннего скролла (продакшен: текст ноды должен быть виден целиком,
// даже длинный, переносом на новую строку — не спрятан в узкой рамке).
// Используется и как ref-колбэк (сразу после монтирования/при каждом
// рендере — раз текст мог поменяться извне), и как onInput (мгновенно,
// пока печатает пользователь, не дожидаясь коммита React).
export function autoGrowTextarea(el) {
  if (!el) return
  el.style.height = 'auto'
  el.style.height = el.scrollHeight + 'px'
}
