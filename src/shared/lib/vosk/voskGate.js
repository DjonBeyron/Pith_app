// «Затвор тишины» для Vosk: длинную паузу в речи не отдаём распознавателю целиком.
// Зачем: эндпойнтер Vosk сидит в декодере (правила model.conf: 0,5 / 1,0 / 2,0 с тишины после слова), vosk-browser его не настраивает (в API только setWords), а у «Сказать фразу»
// закрытый словарь из ЦЕЛЫХ фраз: после «сам закончил» декодер начинает заново с начала фраз, продолжение («to please both») уже не склеить — медленная речь оборвалась бы навсегда.
// Поэтому тишину сверх GATE_KEEP_MS подряд в декодер не шлём: он «видит» паузу не длиннее ≈0,5 с и сам не заканчивает. Конец речи решает наш авто-стоп (voskTiming.js) или правило слова.
// У слушателя слов (wordLaneListen.js) конец речи решает правило слова, и затвор там нужен для другого: телефон не тратит процессор на распознавание тишины между словами.
//
// ЧТО СЧИТАЕТСЯ ЗВУКОМ (v3.3.186; отчёт владельца, iPhone: речь rms 0,003–0,005 при фоне 0,0003 — правило слова голос слышало, а жёсткий порог 0,006 не пускал его в Vosk: 20 попыток «nice»,
// 0 зачётов, 0 черновиков, gatedMs ≈ вся длина захода). Теперь голос определяет тот же счётчик, что и правило слова (voskVoice.js: порог от шума микрофона и пика речи):
//  • voice — счётчик голоса вызывающего (слушатель слов отдаёт счётчик правила слова: голос для правила = звук в Vosk, расхождения быть не может; кусок он получает раньше затвора);
//    без него затвор держит свой счётчик (часы — по длине кусков);
//  • кусок громче GATE_RMS — звук всегда (прежний жёсткий порог остался страховкой: затвор не стал строже ни для кого);
//  • ПРЕДЗВУК: перед первым куском голоса отдаём и последние не отданные куски (GATE_PREROLL_MS): тихое начало слова («s», «h», «f», нарастание 0,0025 → 0,0057 за 250 мс) раньше
//    терялось (возвращался один кусок), и Vosk отдавал первое слово только на следующем звуке (у владельца «see» — через 2,9 с). Длина — по замеру _stand/word_ear; вместе с GATE_KEEP_MS
//    это меньше 0,5 с подряд (самое короткое правило эндпойнта): пауза между словами заход не рвёт;
//  • ХВОСТ: GATE_KEEP_MS тишины после голоса отдаём всегда — Vosk выдаёт слово (черновик), только «увидев» после него тишину.
// Когда в partial уже вся фраза (open), затвор открыт: пусть движок заканчивает сам, как раньше (≈0,5 с) — успех не тормозим. Чистая функция состояния, без React и браузера.
import { createEarVoice } from './voskVoice.js'

export const GATE_RMS = 0.006 // громче — звук при любом шуме (страховка; с включённым шумоподавлением комната ≈0,001–0,004)
export const GATE_KEEP_MS = 300 // столько тишины подряд ещё отдаём распознавателю (3 куска по 128 мс ≈ 384 мс: короче самого короткого правила эндпойнта, 500 мс)
export const GATE_PREROLL_MS = 180 // предзвук: столько не отданного звука перед голосом возвращаем (4 куска по 43 мс при 48 кГц, 3 по 46 мс при 44,1 кГц; не меньше одного куска)

export function createGate({ rmsMin = GATE_RMS, keepMs = GATE_KEEP_MS, prerollMs = GATE_PREROLL_MS, voice: outer = null } = {}) {
  let clock = 0
  const own = outer ? null : createEarVoice({ now: () => clock })
  let quiet = 0 // сколько мс тихо подряд (отданных и нет)
  let dropped = 0 // всего не отдано
  const held = [] // длины последних не отданных кусков (если голос вернулся — они уйдут «предзвуком»)
  return {
    /**
     * Что делать с куском звука: { feed — отдать распознавателю, preroll — сколько предыдущих (не отданных) кусков отдать перед ним: начало слова тише порога, voice — кусок голос по счётчику }.
     * rms — громкость куска, ms — длина, open — затвор открыт (фраза уже вся)
     */
    push(rms, ms, { open = false } = {}) {
      clock += ms
      const voice = own ? own.push(rms).voice : !!outer.heard()
      if (open || voice || rms >= rmsMin) {
        const preroll = held.length
        for (const d of held) dropped -= d
        held.length = 0; quiet = 0
        return { feed: true, preroll, voice }
      }
      const before = quiet
      quiet += ms
      if (before < keepMs) return { feed: true, preroll: 0, voice }
      dropped += ms
      held.push(ms)
      if (held.length > Math.max(1, Math.floor(prerollMs / ms))) held.shift()
      return { feed: false, preroll: 0, voice }
    },
    /** Сколько последних не отданных кусков хранить для предзвука при длине куска ms */
    keep: ms => Math.max(1, Math.floor(prerollMs / Math.max(1, ms))),
    /** Оценка шума микрофона (для автоусиления voskAgc.js) */
    noise: () => (outer ?? own).noise(),
    get droppedMs() { return Math.round(dropped) },
  }
}
