// Автоусиление звука перед Vosk (v3.3.186). Замер на настоящей модели small-en-us-0.15 (16 слов × 3 голоса, без ловушек): Vosk чувствителен к АБСОЛЮТНОЙ громкости — тот же звук
// с тем же отношением сигнал/шум при речи rms 0,0045 (тихий микрофон iPhone владельца: 0,003–0,005) даёт 30 целых слов из 48, ×3 — 39, ×10 — 47, ×30 — 48. Пустить тихий звук в Vosk
// (затвор voskGate.js) мало — его надо поднять. Усиление считается ТОЛЬКО для звука, который уходит в распознаватель: уровень для правила слова, затвора и колец микрофона — прежний.
//  • ПОТОЛОК — от шума микрофона: AGC_TARGET / (шум × AGC_SNR), не больше AGC_MAX. Тихий микрофон (шум 0,0003) — ×27, обычный (шум ≥ 0,008) — ×1: там ничего не меняется.
//  • ОГРАНИЧИТЕЛЬ: кусок после усиления не громче AGC_LIMIT — усиление падает сразу на громком куске и растёт обратно медленно (×AGC_RISE в секунду), поэтому внутри слова оно
//    почти постоянно (огибающая слова не сплющивается); громкая речь на тихом микрофоне не перегружается.
//  • ЗАТВОР ЗАКРЫТ (idle: звук в Vosk не идёт, дольше ≈0,3 с не было голоса) — усиление сразу возвращается к потолку: беречь огибающую не у чего, а следующее слово должно начаться с полного
//    усиления. Без этого громкий звук перед тихой речью (щелчок при открытии микрофона, хлопок пилюли из динамика, одно громкое слово) оставлял усиление ×2–5 на секунды: замер — 23 захода из 192.
//  • Вниз усиление падает С НАЧАЛА громкого куска (иначе его первые миллисекунды ушли бы в Vosk с прежним большим усилением — щелчок на начале слова: замер «See you later» на громком
//    звуке — первый черновик на 140 мс позже); вверх растёт плавно по куску (applyGain) — без ступенек.
// Чистые функции, без браузера. Проверка — voskAgc.test.js и замер _stand/word_ear (CONCEPT_PILLSTAND.md).
export const AGC_TARGET = 0.12 // куда приводим пик тихой речи (rms куска)
export const AGC_SNR = 15      // до первого громкого куска считаем, что речь громче шума микрофона во столько раз
export const AGC_MAX = 32      // усиление не больше
export const AGC_LIMIT = 0.25  // кусок после усиления не громче (rms)
export const AGC_RISE = 2      // усиление растёт обратно не быстрее, раз в секунду

/** noise() — оценка шума микрофона (voskVoice.js; 0 — ещё не знаем: без усиления) */
export function createAgc({ noise }) {
  let g = null, max = 1
  return {
    /** Усиление для куска (rms — его громкость, ms — длина, idle — затвор закрыт: кусок в Vosk не идёт): { from, to } — от начала куска к его концу (при падении from = to) */
    next(rms, ms, idle = false) {
      const n = noise(), cap = n > 0 ? Math.min(AGC_MAX, Math.max(1, AGC_TARGET / (n * AGC_SNR))) : 1
      const from = g ?? cap
      let to = idle ? cap : Math.min(from * AGC_RISE ** (ms / 1000), cap)
      if (rms > 0) to = Math.max(1, Math.min(to, AGC_LIMIT / rms))
      g = to
      if (to > max) max = to
      return { from: Math.min(from, to), to }
    },
    /** Наибольшее усиление за заход (журнал) */
    get max() { return Math.round(max * 10) / 10 },
  }
}

/** Копия куска, умноженная на усиление, которое линейно меняется от from к to */
export function applyGain(data, from, to) {
  const n = data.length, out = new Float32Array(n), step = (to - from) / (n || 1)
  for (let i = 0; i < n; i++) out[i] = data[i] * (from + step * (i + 1))
  return out
}
