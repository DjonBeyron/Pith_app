// «Микрофон игры открывается только из тапа» (iPhone, iOS 18, Safari): после сворачивания приложения iOS заглушает/обрывает игровой поток, а любое getUserMedia вне жеста
// (переоткрытие «оглохшего» микрофона, слушатель следующей ступени, режим 'close') заново показывает диалог доступа. Поэтому пауза игры (useWordLanePause) поднимает флаг «нужен жест»:
// пока он поднят, автоматические пути (оглох → переоткрыть, поток открыть заново после окна речи, слушатель без живого потока) микрофон НЕ открывают. Флаг опускает сам openGameMic — его
// зовёт только жест (тап «Начать» / «Продолжить»). Чистая логика без DOM — состояние в модуле.
let needed = false

export const gameMicGesture = {
  /** Пауза: дальше микрофон открывается только из жеста */
  require() { needed = true },
  /** Жест открыл микрофон (openGameMic) — автоматические пути снова разрешены */
  grant() { needed = false },
  /** Нужен ли жест (автоматически микрофон открывать нельзя) */
  needed: () => needed,
}

/**
 * Обёртка над getGameMic для слушателя: нет живого потока и нужен жест — вместо «распознаватель откроет микрофон сам» (voskEngine: getUserMedia с эхо/шумоподавлением, диалог доступа)
 * отдаём отказ — слушатель сообщит об ошибке. get — getGameMic.
 */
export const guardStream = (get, gate = gameMicGesture) => () => {
  const s = get()
  if (s || !gate.needed()) return s
  return Promise.reject(Object.assign(new Error('микрофон открывается только из тапа'), { name: 'NotAllowedError' }))
}
