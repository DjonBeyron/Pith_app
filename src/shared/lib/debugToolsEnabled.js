// Один выключатель на все дебаг-инструменты (тулбар 🐞, покадровые часы,
// rrweb-запись). Выключен по умолчанию — в том числе в dev.
//
// Зачем флаг, если есть import.meta.env.DEV: в репозиторий уезжает состояние
// «дебаг выключен», и никакая ветка с ним не может случайно оказаться в
// сборке. Включается локально, без правки кода и без следа в git:
//   в .env.local (он в .gitignore) → VITE_DEBUG_TOOLS=1
//
// Обе части известны на этапе сборки, поэтому Vite вырезает ветки целиком —
// в прод-бандл не попадают ни тулбар, ни @sinonjs/fake-timers, ни rrweb.
export const DEBUG_TOOLS_ON = import.meta.env.DEV && import.meta.env.VITE_DEBUG_TOOLS === '1'
