// Для попапа voice === true только булево; всё остальное (undefined, строка) = обычные тексты. В коротком виде строка приватности добавляется ТОЛЬКО в этом режиме (без него там её и не было).
export const PRIVACY_LINE = 'Запись не сохраняется.'
export const PRIVACY_VOICE_LINE = 'Запись остаётся только на вашем телефоне до конца урока.'
// Тексты короткие намеренно: на 320×568 над модулем ≈315px, а блок «Я не могу говорить» уже занимает 4 строки — пояснение должно уложиться в две строки (как в обычном режиме).
// Полный и вводный: одна строка приватности (заголовок уже говорит про микрофон / фразу). Короткий (перед повторным запросом ОС): «Нажмите «Разрешить»» + «остаётся на вашем телефоне» без «только» и «до конца урока» (полный вид с ним ученик уже видел).
const VOICE_LINES = {
  full: [PRIVACY_VOICE_LINE],
  short: ['Нажмите «Разрешить». Запись остаётся на вашем телефоне.'],
  intro: [PRIVACY_VOICE_LINE],
}
const BASE_LINES = { full: EXPLAIN_LINES, short: EXPLAIN_SHORT_LINES, intro: INTRO_LINES }
/** Строки пояснения попапа по виду (full | short | intro, мусор = full) и режиму голосового; чистая функция */
export function pickPopupLines(kind, voice) {
  const k = BASE_LINES[kind] ? kind : 'full'
  return voice === true ? VOICE_LINES[k] : BASE_LINES[k]
}
