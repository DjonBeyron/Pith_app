// Реплика ученика в чат после неудачной попытки (и при успехе с пропущенными словами — successReply внизу) в модуле «Сказать фразу»: то, что распознал движок (главный вариант, тот же, по которому
// судили, — judgeRun/alts[0]). Чистая функция, без React. Тишина, ошибка движка и пустой результат реплики не дают (null) — тогда в чат
// идёт только подсказка (sayHints.js). Звук не сохраняется; текст остаётся в переписке урока, как любой ответ ученика, на сервер не уходит.

/** Текст реплики для чата или null. verdict — результат judgeRun (поле heard); первая буква заглавная, пробелы схлопнуты */
export function userReply(verdict) {
  const text = String(verdict?.heard ?? '').replace(/\s+/g, ' ').trim()
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : null
}

/**
 * Реплика ученика в чат при УСПЕХЕ (вместо подстановки эталона). Эталон показываем, только когда все его слова реально услышаны (verdict.missed пуст — опечатки в пределах допуска тоже «услышаны»).
 * Порог допускает пропуск слов (4 из 5 при 70%) — тогда ученик НЕ должен видеть в чате фразу целиком, которой он не говорил: показываем то, что услышал движок (как при неудаче).
 * Нет вердикта (админская палочка «засчитать», пропуск) или нет услышанного текста — эталон как был.
 */
export function successReply(verdict, phrase) {
  if (!verdict || !Array.isArray(verdict.missed) || verdict.missed.length === 0) return phrase
  return userReply(verdict) ?? phrase
}
