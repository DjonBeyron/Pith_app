// Реплика ученика в чат после неудачной попытки в модуле «Сказать фразу»: то, что распознал движок (главный вариант, тот же, по которому
// судили, — judgeRun/alts[0]). Чистая функция, без React. Тишина, ошибка движка и пустой результат реплики не дают (null) — тогда в чат
// идёт только подсказка (sayHints.js). Звук не сохраняется; текст остаётся в переписке урока, как любой ответ ученика, на сервер не уходит.

/** Текст реплики для чата или null. verdict — результат judgeRun (поле heard); первая буква заглавная, пробелы схлопнуты */
export function userReply(verdict) {
  const text = String(verdict?.heard ?? '').replace(/\s+/g, ' ').trim()
  return text ? text.charAt(0).toUpperCase() + text.slice(1) : null
}
