// Русский вариант сравнения слов для распознавания Vosk (проход «назови перевод» игры «Встряхни память»): tokenize из speechMatch.js стирает всё, кроме латиницы, поэтому для кириллицы свой разбор.
// Чистые функции без React. Сравнение — по словам: строчные, «ё» ≡ «е», знаки препинания убраны, дефис внутри слова разделяет слова («кто-то» → кто, то: Vosk отдаёт их отдельно).
// Перевод в карточке бывает с вариантами и пометками: «пытаться, стараться», «бегать / бежать», «встретить (кого-то)». Ученик говорит ОДИН вариант, поэтому цель — любой из вариантов (altsRu),
// а пометка в скобках не произносится. Раньше вся строка шла одной фразой («пытаться стараться»): сказанный вариант с целью не совпадал никогда.

/** Строка → слова: нижний регистр, ё → е, только буквы и цифры, остальное — разделитель */
export function tokenizeRu(text) {
  return String(text ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .split(/\s+/)
    .filter(Boolean)
}

/** Нормализованная строка для сравнения переводов («Ёлка!» → «елка») */
export const normTextRu = text => tokenizeRu(text).join(' ')

const ALT_SPLIT = /[/,;|\n]|\s+или\s+/i   // разделители вариантов перевода
const NOTE = /\([^)]*\)|\[[^\]]*\]/g     // пометки в скобках: (кого-то), [разг.]

/**
 * Варианты перевода, которые ученик может сказать: «пытаться, стараться» → ["пытаться", "стараться"]; «встретить (кого-то)» → ["встретить"]; «бегать / бежать» → ["бегать", "бежать"]. Регистр и «ё» сохраняются
 * (запись для словаря Vosk). Без вариантов — сама строка; весь перевод в скобках — он как есть; пусто — []. Повторы убраны.
 */
export function altsRu(text) {
  const raw = String(text ?? '')
  const parts = raw.replace(NOTE, ' ').split(ALT_SPLIT).map(s => s.trim()).filter(s => tokenizeRu(s).length)
  const list = parts.length ? parts : [raw.trim()].filter(s => tokenizeRu(s).length)
  const seen = new Set()
  return list.filter(s => { const k = normTextRu(s); if (seen.has(k)) return false; seen.add(k); return true })
}

/** Сколько слов в самом коротком варианте перевода (не меньше 1): «добрый день» → 2, «пытаться, стараться» → 1 */
export function wordCountRu(text) {
  const n = altsRu(text).map(a => tokenizeRu(a).length)
  return n.length ? Math.max(1, Math.min(...n)) : 1
}

/**
 * Записи цели для словаря Vosk (русская модель): каждый вариант перевода (altsRu) как записан и без «ё» — модель могла выучить слово в любой из двух записей («ещё» / «еще»); слова, которых нет в словаре модели, она сама игнорирует.
 * Каждый вариант — отдельно строчными: «Я пытаюсь» → ["я пытаюсь"]; «ещё» → ["ещё", "еще"]; «пытаться, стараться» → ["пытаться", "стараться"]. Пустая строка → [].
 */
export function phraseFormsRu(text) {
  const out = []
  for (const alt of altsRu(text)) {
    const a = alt.toLowerCase().replace(/[^\p{L}\p{N}\s]/gu, ' ').split(/\s+/).filter(Boolean).join(' ')
    const b = a.replace(/ё/g, 'е')
    for (const f of a === b ? [a] : [a, b]) if (f && !out.includes(f)) out.push(f)
  }
  return out
}
