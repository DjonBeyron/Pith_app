// Оповещение «урок сохранён» для тех, кто показывает его данные рядом.
//
// Схема модуля (useCurriculumLessons) читает список уроков из базы один раз —
// при смене состава уроков. Редактор открывается ПОВЕРХ неё, список всё это
// время висит смонтированным, поэтому переименование урока в канвасе доходило
// до схемы только после перезагрузки приложения. Теперь редактор сообщает о
// сохранении, а список поправляет у себя название и XP — без похода в базу.
//
// Подписка модулем, а не React-контекстом: CurriculumView живёт в четырёх
// разных местах (лента, профиль, админка, гонка), и тащить проп через каждое
// ради одного события смысла нет.
const listeners = new Set()

export function onLessonSaved(fn) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

export function notifyLessonSaved(lesson) {
  if (!lesson?.id) return
  for (const fn of listeners) {
    try { fn(lesson) } catch { /* один слушатель не должен ронять остальных */ }
  }
}
