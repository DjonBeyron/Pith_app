// «Режим пользователя»: админ временно смотрит на приложение глазами ученика.
//
// Нужен для проверки — увидеть ровно то, что видит ученик, не заводя второй
// аккаунт и не выходя из своего. Пока режим включён, весь админский интерфейс
// спрятан: карандаши на нодах, кнопки публикации, панель шага в плеере,
// «продолжить редактирование», скачивание лога. Остаётся одна кнопка «Админ»
// в нижней панели — ею же режим и выключается обратно.
//
// Это ТОЛЬКО про интерфейс. Настоящие права живут в БД (политики RLS), и
// подделать их отсюда нельзя: запрос от админа с включённым режимом сервер
// по-прежнему выполнит. Поэтому флаг и лежит в localStorage — терять его
// между вкладками не страшно, а вот пережить перезагрузку он обязан, иначе
// проверять сценарий ученика было бы невозможно.

const KEY = 'pithy_user_mode_v1'

const subs = new Set()

export function getUserMode() {
  try { return localStorage.getItem(KEY) === '1' } catch { return false }
}

export function setUserMode(on) {
  try {
    if (on) localStorage.setItem(KEY, '1')
    else localStorage.removeItem(KEY)
  } catch { /* приватный режим — тогда флаг живёт только до перезагрузки */ }
  subs.forEach(fn => fn())
}

// useSyncExternalStore: значение меняется вне React (localStorage), а
// подписчиков может быть много — провайдер один, но вкладки в пределах
// страницы перерисовываются все разом
export function subscribeUserMode(fn) {
  subs.add(fn)
  return () => subs.delete(fn)
}
