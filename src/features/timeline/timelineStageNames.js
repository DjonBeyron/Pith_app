/** Стадия вырезанного круга «Пойми · Тапни фразу» (sid phrases1, phrases1-ann): в сценарий и в «Прослушать» не идёт. Круг «Скажи» (phrases2) — идёт */
export const isCutStage = sid => /^phrases1(-|$)/.test(String(sid ?? ''))

/** sid → { name, kind?, anim? } или null (неизвестная стадия) */
export function stageInfo(sid) {
  const id = String(sid ?? '')
  if (Object.hasOwn(STAGE_NAMES, id)) return STAGE_NAMES[id]
  const k = id.match(/^climb-(\d+)$/)
  return k ? { name: `Вершина — ступень ${k[1]}` } : null
}

/** Название стадии для админа: s — стадия модели ({ sid, title }) или sid строкой; неизвестная — sid как есть (с заголовком плашки, если он был); null — «до первой стадии» */
export function stageTitle(s) {
  if (s == null) return 'до первой стадии'
  const sid = typeof s === 'string' ? s : s.sid ?? '', info = stageInfo(sid)
  return info ? info.name : `${sid || '—'}${typeof s !== 'string' && s.title ? ` «${s.title}»` : ''}`
}

/** Название этапа (акта) для админа: «Конвейер слов», «Фразы»…; неизвестный — как есть */
export const actTitle = act => ACT_NAMES[act] ?? (act || 'до первой стадии')
