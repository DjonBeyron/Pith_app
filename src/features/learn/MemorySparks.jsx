// Искры над пятиугольником постоянной памяти — как от костра: мелкие фиолетовые
// огоньки быстро взлетают от его верха, чуть вихляют, мерцают, сжимаются и гаснут;
// в кадре 3–5. Только CSS-анимации transform и opacity на отдельных слоях — их
// считает композитор, без перерисовки и без JS на кадр; на скрытой вкладке и
// при «меньше движения» не идут (memory-perm.css).
// Искра — две вложенные: внешняя взлетает (быстро в начале, к концу
// замедляется), сжимается и гаснет; внутренняя вихляет и мерцает (свои периоды
// — траектории не повторяются в такт; старты разведены равномерно, периоды чуть
// разные — в кадре почти всегда 3–5). x — % ширины, s — размер (px),
// r — на сколько взлетает (px), d — период (с), dl — сдвиг старта (с),
// sw — размах вихляния (px), c — цвет
const SPARKS = [
  { x: 24, s: 2.4, r: 190, d: 3.4, dl: 0, sw: 7, c: '#f1eaff' },
  { x: 38, s: 3, r: 150, d: 3.7, dl: -0.6, sw: 6, c: '#d9ccff' },
  { x: 50, s: 2.2, r: 210, d: 3.5, dl: -1.2, sw: 8, c: '#ffffff' },
  { x: 62, s: 2.8, r: 165, d: 3.9, dl: -1.8, sw: 6, c: '#c4b5fd' },
  { x: 75, s: 2.2, r: 195, d: 3.6, dl: -2.4, sw: 7, c: '#e6deff' },
  { x: 86, s: 2.6, r: 140, d: 3.8, dl: -3, sw: 5, c: '#cfc2ff' },
]

export default function MemorySparks() {
  return (
    <span className="memSparkBox" aria-hidden="true">
      {SPARKS.map(a => (
        <span key={a.x} className="memSpark" style={{ '--x': `${a.x}%`, '--r': `${a.r}px`, '--d': `${a.d}s`, '--dl': `${a.dl}s` }}>
          <i style={{ '--s': `${a.s}px`, '--sw': `${a.sw}px`, '--c': a.c }} />
        </span>
      ))}
    </span>
  )
}
