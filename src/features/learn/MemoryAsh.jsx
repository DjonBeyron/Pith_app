// «Пепел» над пятиугольником постоянной памяти: пять фиолетовых искорок
// медленно поднимаются от его верха, качаются из стороны в сторону и гаснут —
// в каждый момент видно 3–5. Только CSS-анимации transform и opacity на
// отдельных слоях — их считает композитор, без перерисовки и без JS на кадр;
// на скрытой вкладке и при «меньше движения» не идут (memory-perm.css); искорки
// чётко видны (4–5.5 px со свечением), но редкие — это «пепел», а не метель.
// Искорка — две вложенные: внешняя поднимается и гаснет, внутренняя качается
// (разные периоды — траектории не повторяются в такт). x — % ширины, s — размер,
// r — на сколько поднимается (px), d — период (с), dl — сдвиг старта (с),
// sw — размах качания (px), c — цвет
const ASH = [
  { x: 22, s: 4.5, r: 86, d: 11, dl: -2, sw: 6, c: '#d9ccff' },
  { x: 40, s: 5.5, r: 92, d: 13, dl: -9, sw: 7, c: '#c4b5fd' },
  { x: 55, s: 4, r: 80, d: 10, dl: -5, sw: 5, c: '#efe9ff' },
  { x: 70, s: 5, r: 90, d: 12, dl: -1, sw: 7, c: '#b9a4fb' },
  { x: 84, s: 4.2, r: 82, d: 14, dl: -7, sw: 6, c: '#cfc2ff' },
]

export default function MemoryAsh() {
  return (
    <span className="memAshBox" aria-hidden="true">
      {ASH.map(a => (
        <span key={a.x} className="memAsh" style={{ '--x': `${a.x}%`, '--r': `${a.r}px`, '--d': `${a.d}s`, '--dl': `${a.dl}s` }}>
          <i style={{ '--s': `${a.s}px`, '--sw': `${a.sw}px`, '--c': a.c }} />
        </span>
      ))}
    </span>
  )
}
