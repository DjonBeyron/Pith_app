// Сколько шариков «слов к повтору» бежит по кабелю одновременно. Жёсткий потолок — три: по одному
// на каждую из трёх ступеней памяти (новые / знакомые / усвоенные). Больше на телефоне не нужно: шариков
// на одной линии и так не различить, а каждый — это три анимируемых слоя
export const MAX_FLYING_BALLS = 3

// today — число сегодняшних слов по ступеням ([новые, знакомые, усвоенные]).
// → индексы ступеней, у которых сегодня есть слова: по одному шарику на ступень, не больше MAX_FLYING_BALLS.
// Чистая функция: мусор на входе (не массив, NaN, отрицательные) даёт пустой/усечённый список, а не падение
export function flyingBalls(today) {
  const out = []
  if (!Array.isArray(today)) return out
  for (let i = 0; i < today.length && out.length < MAX_FLYING_BALLS; i++) {
    if (today[i] > 0) out.push(i)
  }
  return out
}

// Размер и вид шарика на ступени i: длительность пролёта растёт на 0,3 с на ступень, старт сдвинут на 0,1 с —
// шарики трёх ступеней не бегут в ногу
export const ballTiming = i => ({ dur: `${(2.6 + i * 0.3).toFixed(1)}s`, delay: `${(i * 0.1).toFixed(2)}s` })
