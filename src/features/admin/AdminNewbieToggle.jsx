import { isNewbieSim, setNewbieSim } from '../../shared/lib/newbieSim.js'
import AdminToggleRow from './AdminToggleRow.jsx'

// Переключатель «Я новенький» (newbieSim.js): приложение ведёт себя так, как будто его впервые открыл новый человек —
// подсказки и знакомства показываются заново, XP, уровень, пройденные уроки, память слов и фразы пусты. Данные
// аккаунта не удаляются: выключил — всё на месте. Страница перезагружается (песочница подключается на старте)
export default function AdminNewbieToggle() {
  return (
    <AdminToggleRow
      title="Я новенький (первый вход)"
      on={isNewbieSim()}
      onChange={setNewbieSim}
      hint="Приложение поведёт себя как у человека, впервые его открывшего: знакомства и подсказки заново, XP, уровень и прогресс пусты. Твои данные не удаляются. Страница перезагрузится."
      hintOn="Ты «новенький»: данные аккаунта не затронуты, прогресс копится отдельно. Выключи — всё вернётся. Вход и регистрацию в этом режиме не трогай."
    />
  )
}
