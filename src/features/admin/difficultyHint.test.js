import { describe, it, expect } from 'vitest'
import { difficultyHint } from './difficultyHint.js'

// Подсказка рядом с чипом «Сложность»: сколько голосов и что важнее
describe('difficultyHint', () => {
  it('голосов нет — действует выбор админа', () => {
    expect(difficultyHint(0, null, null)).toBe('голосов нет: действует выбор админа')
  })
  it('мало голосов — сколько из скольких, пока действует выбор админа', () => {
    expect(difficultyHint(3, 2, 1)).toBe('голосов 3 из 5: пока действует выбор админа')
  })
  it('голосов от порога — число, медиана и что голоса важнее; выбор админа упомянут, если он есть', () => {
    expect(difficultyHint(5, 3, null)).toBe('голоса: 5, медиана 3 (сложная) — голоса важнее выбора админа')
    expect(difficultyHint(12, 2, 1)).toBe('голоса: 12, медиана 2 (средняя) — голоса важнее выбора админа, он сейчас 1')
  })
})
