// Промпт-заготовка для нейросети (вкладка «Для нейросети» сборщика): вставляется после
// легенды sceneLegendText(). topic — тема от админа; пусто — плейсхолдер <тема>.
// withTask — попросить заодно задание «О чём диалог»: translation у каждой реплики и поле task.
// withVars — шаблон сцены под слова пользователя (блок «Слова пользователя»): поле vars и плейсхолдеры {ключ}/{ключ:ru} (см. легенду).
export function buildPrompt(topic, { withTask = false, withVars = false } = {}) {
  const t = String(topic ?? '').trim() || '<тема>'
  return [
    `Сделай сцену по этой легенде на тему: ${t}.`,
    'Диалог из 4–6 реплик (минимум 2; для заданий «Повтори за диктором»/«Ответь коту» достаточно одной), два персонажа чередуются, каждая реплика до 110 символов и заканчивается знаком препинания.',
    'Эмоции меняются по ходу сцены; у сцены есть завязка, поворот и развязка-шутка или договорённость.',
    'Предметы в слотах поддерживают тему, все слоты пустыми не оставляй; персонажи отличаются полом или цветом шерсти.',
    ...(withTask ? [
      'Добавь задание «О чём диалог»: у КАЖДОЙ реплики заполни translation (перевод на русский), а в поле task укажи kind "translate",',
      'lineIndex реплики с поворотом или развязкой, prompt вида «Что сказал(а) <имя>?», 2–4 accept (другие верные формулировки перевода) и hint без самого ответа.',
      'Голосовые задания: task.kind может быть "repeat" (повтор за диктором — выбери короткую реплику до 12 слов; translation не нужен) или "say" (ответ коту — lineIndex на реплику-вопрос, answers 1–3 ожидаемых ответа на языке оригинала, при желании keywords до 12 слов и hint); passRatio 0.6–0.85 и strict — необязательно.',
    ] : []),
    ...(withVars ? [
      'Сделай ШАБЛОН под слова пользователя: добавь поле vars (1–3 слова пользователя, ключи вроде food) — у каждого pick ("weak" | "due" | "known") (weak — новые слова, due — пора повторить, known — знакомые и выше) и обязательный fallback { text, translation } — запасное слово.',
      'В репликах пиши {ключ} в text и {ключ:ru} в translation (у каждой шаблонной реплики заполни translation); реплика должна быть верной с любым словом, артикль включай в слово; задание task не добавляй; поле segments не заполняй.',
    ] : []),
    'Поля озвучки (audioUrl, wordTimings, audioMeta, такие же поля для перевода, voiceId и настройки голоса ElevenLabs) не заполняй — их ставит сборщик.',
    'Если реплики на иностранном языке — у каждой заполни русский перевод и в options выставь режим показа display ("text" | "both") и флаги озвучки voice по смыслу сцены (см. легенду).',
    'Ответ — только JSON сцены (version 2) без пояснений и без markdown.',
  ].join('\n')
}

// Ответ нейросети часто обёрнут в ```json … ``` — снимаем обёртку перед разбором
export function stripCodeFence(text) {
  const m = /```(?:json)?\s*([\s\S]*?)```/i.exec(String(text ?? ''))
  return (m ? m[1] : String(text ?? '')).trim()
}
