import { TEMPLATE_FILES } from '../designerTemplates.js'
import { PACK_FILES } from './packConsts.js'

// Куски печатного документа, которых нет в React-разделах админки: титул с оглавлением,
// миниатюры SVG-шаблонов (сам SVG inline — файл остаётся автономным), «как пользоваться
// проверкой», подвал. Чистые строки HTML; числа приходят из packConstants (buildPrintDoc).

const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

export const DOC_TITLE = 'Спрайты для Pithy: спецификация для дизайнера'

export const TOC = [
  ['how', 'Как работать — 5 шагов, как это будет в приложении, хорошо / плохо'],
  ['spec', 'Спецификация: холст, группы, рот и эмоции, якоря и слои, цвета, запреты, бюджет, имена файлов'],
  ['templates', 'Шаблоны SVG: кот, предмет напольный, предмет настенный'],
  ['check', 'Проверка файла перед отправкой'],
  ['dev', 'Для программиста / админа: как добавить спрайт (дизайнеру читать не нужно)'],
]

export function titleBlock(c, dateText) {
  return `
<h1>${DOC_TITLE}</h1>
<p class="lead">Сцена «два кота говорят» в приложении Pithy рисуется из плоских SVG-файлов: два кота, предметы в именованных ячейках и фон.
Этот документ — всё, что нужно, чтобы нарисовать свои: размеры, имена групп, формы рта, якоря, запреты и бюджет. Числа в нём взяты из кода приложения, поэтому совпадают с автоматической проверкой.</p>
<p class="meta">Версия приложения ${esc(c.version)} · ${esc(dateText)} · файлы пакета: ${esc(PACK_FILES.checker)} (проверка), ${esc(PACK_FILES.templates)} (шаблоны)</p>
<ol class="toc">${TOC.map(([id, t]) => `<li><a href="#p-${id}">${esc(t)}</a></li>`).join('')}</ol>`
}

export function templatesBlock() {
  return `
<section class="part" id="p-templates"><h2 class="partH">Шаблоны SVG</h2>
<div class="block"><p>Шаблон — готовый SVG с подписанными группами <code>data-part</code> / <code>data-viseme</code> и бледным пунктирным контуром-подсказкой. Откройте в редакторе, рисуйте внутри групп, контур удалите.
Файлы выдаёт администратор (кнопки «Скачать» в приложении или один файл ${esc(PACK_FILES.templates)} с кнопками «Скачать» у каждого шаблона).</p>
<div class="tpl">${TEMPLATE_FILES.map(t => `<figure>${t.make().replace(/<\?xml[^>]*>/, '')}<figcaption><b>${esc(t.title)}</b><br><code>${esc(t.file)}</code></figcaption></figure>`).join('')}</div>
<p class="scHint">Кот ♀ — тот же шаблон кота: отличия (бантик, ресницы, стройнее хвост) рисуются внутри тех же групп, файл называется cat-female.svg.</p>
</div></section>`
}

export function checkBlock(c) {
  const K = c.SPRITE_KINDS
  return `
<section class="part" id="p-check"><h2 class="partH">Проверка файла перед отправкой</h2>
<div class="block"><p class="blockH">Файл ${esc(PACK_FILES.checker)}</p>
<p>Один HTML-файл, открывается двойным кликом в любом браузере, без интернета, ничего никуда не отправляет. Проверка в нём — тот же код, что в приложении: зелёный вердикт у вас = зелёный у администратора.</p>
<ol class="scList">
<li>Откройте файл, выберите тип (кот / предмет / фон — определяется сам) и загрузите SVG кнопкой, перетаскиванием или вставьте текст.</li>
<li>Вердикт: <b>«Можно отправлять»</b> — готово; <b>«Исправьте N пунктов»</b> — у каждого пункта написано, как исправить (например, «уберите фильтры и тени; тень нарисуйте плоским эллипсом»).</li>
<li>Полоса бюджета: сколько узлов из лимита (кот ≤ ${K.cat.maxNodes}, предмет ≤ ${K.prop.maxNodes}, фон ≤ ${K.background.maxNodes}). Ниже — найденные группы: обязательные, которых нет, зачёркнуты красным.</li>
<li>Предпросмотр: кот дышит, моргает, качает хвостом и головой — ровно как в приложении; переключатели формы рта (closed / half / open), режим «Говорит» (рот чередуется каждые ${c.MOUTH_STEP_MS} мс), эмоция, пауза, скорость, тёмный фон, масштаб. Предмет ставится в ячейку «на столе / на стене / на полу / под потолком» красной точкой-якорем: сразу видно, стоит он или висит в воздухе.</li>
<li>Назовите файл латиницей через дефис (cat-male.svg, coffee-cup.svg, bg-cafe.svg) и отправьте администратору.</li>
</ol></div></section>`
}

