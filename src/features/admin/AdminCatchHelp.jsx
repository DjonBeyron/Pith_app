const LEVELS = [
  ['0', 'серый', 'слова нет в памяти', '0'],
  ['1', 'зелёный', 'шаг 1–2', '1'],
  ['2', 'синий', 'шаг 3–4', '2–3'],
  ['3', 'золотой', 'шаг 5', '4–5'],
  ['4', 'фиолетовый', 'постоянная память', 'вся клавиатура'],
]

