// Сигнал «сегодня закрыт первый день в жизни аккаунта».
//
// Ставит его плеер (useLessonFinish, по ответу bump_streak_on_lesson), а
// забирает схема уроков — но не сразу: окно «Путь начат» должно появиться
// ПОСЛЕ анимации графа (прилёт XP, открытие следующего урока), иначе оно
// перекроет главный момент — то, ради чего урок и проходили.
//
// Обычная переменная в модуле, а не localStorage: сигнал живёт секунды, между
// двумя экранами одной сессии, и переживать перезагрузку ему незачем (а
// заодно не превращается в залипший флаг, если что-то пойдёт не так).
let pending = false

export function markFirstDay() {
  pending = true
}

// Забрать и погасить: второй вызов вернёт false, поэтому окно не покажется
// дважды, даже если анимация графа отработает повторно.
export function takeFirstDay() {
  if (!pending) return false
  pending = false
  return true
}
