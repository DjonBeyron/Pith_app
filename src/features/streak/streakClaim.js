// Есть ли неполученная награда серии: так же считает окно наград (RewardsPopup: «Забрать награду» доступна, пока серия
// длиннее уже полученных дней). По этому признаку в профиле блестит блок «Ежедневные награды»
export const hasUnclaimedStreak = profile => (profile?.current_streak ?? 0) > (profile?.last_claimed_streak_day ?? 0)

// Где в пути дней окна наград стоит указатель «ты здесь» (треугольник + пунктир). Возвращает номер строки, НАД которой он
// рисуется (граница между строками i-1 и i), либо -1 — указателя нет. Правило: указатель всегда ВПЕРЕДИ (ниже) последнего
// блока, который получен ИЛИ уже доступен для получения: есть блоки «можно забрать» — он под последним из них, всё
// доступное получено — под последним полученным. Иначе говоря, на границе «открыто (получено / можно забрать) | впереди».
// firstDay..lastDay — дни, которые показывает путь; claimedDay — last_claimed_streak_day; streak — current_streak.
// Берём max(claimedDay, streak): после срыва серии streak = 0, а claimedDay может остаться выше — полученные дни всё равно позади.
// Нет открытых дней в окне (серия 0, ничего не получено) или открыты все показанные (ниже края окна указывать не на что) — -1.
export function pointerIndex(firstDay, lastDay, claimedDay, streak) {
  const count = lastDay - firstDay + 1
  const idx = Math.max(claimedDay ?? 0, streak ?? 0) - firstDay + 1
  return idx > 0 && idx < count ? idx : -1
}
