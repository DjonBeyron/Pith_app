// Подсказка следующего слова в проходе 1 «Скажи» (замечание владельца 2026-11-08: «пока говорю слово k, слово k+1 начинает проявляться по буквам, не ярче 30 %; сказал — оно целиком,
// и проявляется k+2»). Какое слово — racePhraseMask.nextPeek (первое спрятанное после самого дальнего услышанного; открытые сразу короткие слова пропускаются); вид — data-w='peek'
// (race-phrase-rounds.css: opacity 0,3 и маска-градиент по --peek). Проявление ведёт этот модуль: --peek растёт 0 → 100 % за PEEK_MS от момента, когда слово стало подсказкой, — каждый кадр,
// только у одной ячейки (maskView.peek пишет при смене).
// С ПЕРВОГО КАДРА ПИЛЮЛИ (замечание владельца 2026-11-08, «логика подсказки букв неверная»): пилюля «Скажи» появилась — слово 1 открыто, а следующее спрятанное (слово 2) сразу проявляется,
// не дожидаясь голоса или слова 1. Сказано слово 1 — ничего не меняется (подсказка остаётся); сказано подсказанное — оно целиком, подсказка переходит дальше; перепрыгнул — на первое
// спрятанное после самого дальнего услышанного. В проходе 2 подсказки нет (текст открыт). Время — аргументом.
import { nextPeek } from './racePhraseMask.js'

export const PEEK_MS = 1200

/** → { show(heard, t), frame(t), index() }. mask — маска пилюли (racePhraseMaskView: set(heard, all, peek), peek(pct)); text — фраза; t — кадр появления пилюли (подсказка начинается сразу) */
export function createPeek({ mask, text, t = 0 }) {
  let idx = -1, at = t
  const show = (heard, now) => {
    const i = nextPeek(text, heard)
    if (i !== idx) { idx = i; at = now }
    mask?.set(heard, false, idx)
    return idx
  }
  show(new Map(), t)
  return {
    /** Услышано слово: маска перерисована (heard — Map номер слова → подтверждено ли), подсказка — следующее спрятанное (то же слово — проявление продолжается) */
    show,
    /** Кадр: проявление подсказки по буквам */
    frame(now) { if (idx >= 0) mask?.peek(((now - at) / PEEK_MS) * 100) },
    /** Какое слово сейчас подсказано (-1 — никакое) */
    index: () => idx,
  }
}
