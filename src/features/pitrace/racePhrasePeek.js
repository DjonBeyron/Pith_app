// Подсказка следующего слова в проходе 1 «Скажи» (решение владельца 2026-11-09, пример «I want to»): пока ничего не сказано — подсказки нет (первое слово открыто, остальные — кирпичики).
// Сказано верно слово k (черновиком или итогом: оно целиком белое) — ТОЛЬКО ТОГДА слово k+1 начинает проявляться: не по буквам, а ЦЕЛЫМ словом через opacity, плавно (ease-out за PEEK_MS)
// от 0 до PEEK_MAX (20 % — еле видно) и там остаётся, пока слово не сказано. Сказано k+1 — оно белое, проявляется k+2; последнее — подсказывать нечего. Цепочка строго по порядку:
// подсказка — только у первого не сказанного по порядку слова, там же, где линия заливки (racePhraseMask.nextPeek, с 2026-11-09 — не за самым дальним сказанным; открытое сразу короткое слово не подсказывается — оно и так видно). Вид — data-w='peek' и --peek
// (race-phrase-rounds.css: opacity: var(--peek)), значение пишет maskView.peek только при смене. Отменяет подсказку «с первого кадра пилюли» по буквам до 30 % (v3.3.170). В проходе 2 подсказки нет.
import { nextPeek } from './racePhraseMask.js'

export const PEEK_MS = 1200
export const PEEK_MAX = 0.2

/** Проявление подсказки через ms мс после старта: 0 → PEEK_MAX, ease-out (кубическая), дальше стоит */
export const peekLevel = ms => PEEK_MAX * (1 - (1 - Math.min(1, Math.max(0, ms) / PEEK_MS)) ** 3)

/** → { show(heard, t), frame(t), index() }. mask — маска пилюли (racePhraseMaskView: set(heard, all, peek), peek(level)); text — фраза. Подсказка стартует только по сказанному слову (show) */
export function createPeek({ mask, text }) {
  let idx = -1, at = 0
  return {
    /** Услышано слово: маска перерисована (heard — Map номер слова → подтверждено ли), подсказка — первое не сказанное по порядку (то же слово — проявление продолжается) */
    show(heard, now) {
      const i = nextPeek(text, heard)
      if (i !== idx) { idx = i; at = now }
      mask?.set(heard, false, idx)
      return idx
    },
    /** Кадр: проявление подсказки целым словом (0 → PEEK_MAX) */
    frame(now) { if (idx >= 0) mask?.peek(peekLevel(now - at)) },
    /** Какое слово сейчас подсказано (-1 — никакое) */
    index: () => idx,
  }
}
