// Удержание ПОСЛЕДНЕГО слова фразы в черновике (проход 1 «по слову», v3.3.314; владелец: «слишком предсказывает Vosk, особенно в последнем слове фразы»). Журнал 2026-11-20: первый черновик захода Vosk
// часто угадывает по первому звуку и через 170–270 мс переписывает («is» → «the», «in» → «brother», «can» → «me», «what» → «your»). Для середины фразы это не страшно (слово откатится), а последнее слово сразу
// закрывает фразу: «100 % через 97 мс, последнее слово пришло черновиком». Правило: последнее слово фразы, стоящее ХВОСТОМ черновика, принимается, только когда хвост не менялся TAIL_HOLD_MS; итог захода принимает сразу.
// v3.3.317 (журнал владельца 23:26: сказал «фриз» вместо «from» — черновик «you from» устоялся и фраза засчиталась): устоявшийся черновик тоже врёт (закрытый словарь подставляет слово цели), а итог захода чужое слово
// отдаёт как «[unk]» (там же: черновик «are you you» → итог «are you [unk]»). Поэтому последнее слово черновиком не принимается ВОВСЕ: хвост устоялся — слушатель просит итог захода (≈ 100 мс), решает итог.
// Чистая логика над часами now(): таймер повторной проверки ведёт слушатель (racePhraseListen.js).
export const TAIL_HOLD_MS = 300
// v3.3.380 (владелец: «задержка, когда составляю фразу полностью»; журнал 26.11: от последнего слова в черновике до зачёта 468–499 мс, из них 300 — это TAIL_HOLD_MS): итог просим только для того, чтобы решить слово, — черновик не принимается вовсе
// (v3.3.317), так что 300 мс нужны лишь затем, чтобы не оборвать ещё говорящееся слово. Для ПОСЛЕДНЕГО слова это проверяем напрямую: хвост не менялся TAIL_LAST_STABLE_MS и голоса нет TAIL_LAST_QUIET_MS — итог просим сразу;
// голос ещё идёт — ждём, но не дольше прежних TAIL_HOLD_MS. Защита от «угаданного» слова не ослаблена: решает по-прежнему итог захода.
export const TAIL_LAST_STABLE_MS = 150
export const TAIL_LAST_QUIET_MS = 150

/** Через сколько мс перепроверить хвост перед просьбой итога (0 — просим сейчас). first — придержано не последнее слово (ждём паузу голоса TAIL_HOLD_MS), left — сколько хвосту ещё стоять до TAIL_HOLD_MS, sinceVoice — мс с последнего громкого куска */
export const tailWait = ({ first, left, sinceVoice }) => (first ? (sinceVoice < TAIL_HOLD_MS ? 100 : 0) : (left > 0 && sinceVoice < TAIL_LAST_QUIET_MS ? 50 : 0))

export function createTailHold({ now = () => Date.now(), holdMs = TAIL_HOLD_MS } = {}) {
  let key = '', at = -Infinity
  return {
    /** Новый черновик захода: хвост — его последнее слово (и место в заходе) */
    partial(text) { const ws = String(text ?? '').split(/\s+/).filter(Boolean), k = `${ws.length}|${ws[ws.length - 1] ?? ''}`; if (k !== key) { key = k; at = now() } },
    /** Итог захода / новый заход / сброс */
    clear() { key = ''; at = -Infinity },
    /** Сколько мс хвосту ещё стоять (0 — устоялся или хвоста нет) */
    left: (ms = holdMs) => (key ? Math.max(0, ms - (now() - at)) : 0), // ms — сколько должен простоять хвост (по умолчанию TAIL_HOLD_MS)
  }
}

/** Текст без последнего слова */
export const cutTail = text => String(text ?? '').split(/\s+/).filter(Boolean).slice(0, -1).join(' ')

/** Разбор full (с хвостом) → тот же, но слово, которое держится ТОЛЬКО на хвосте черновика (без хвоста — разбор cut — его нет), снято. → { scores, held: [ключи кандидатов, где слово придержано], first: придержано не последнее слово фразы }.
 * all = true (игра, v3.3.322) — любое такое слово; false — только последнее слово фразы (v3.3.314). История: v3.3.321 — первое слово (шум, дыхание, щелчок давали черновик «where», итог его не подтверждал);
 * v3.3.322 (журнал владельца 13:03: «явно сказал is на третьем слове, а он засчитал you» — черновик «are you», итог «are [unk]») — каждое: хвост черновика — догадка закрытого словаря, чужое слово честно называет только итог. */
export function holdLast(full, cut, all = true) {
  const held = []
  let first = true // придержано не последнее слово фразы: итог просим после паузы голоса, чтобы не рвать слитную речь
  const scores = full.map((s, n) => {
    const last = s.hits.length - 1
    const drop = s.hits.map((h, i) => (h && !cut[n]?.hits[i] && (all || i === last) ? i : -1)).filter(i => i >= 0)
    if (!drop.length) return s
    held.push(s.key); if (drop.includes(last)) first = false
    const hits = s.hits.map((h, k) => h && !drop.includes(k)), ok = hits.filter(Boolean).length
    return { ...s, hits, ok, ratio: hits.length ? ok / hits.length : 0 }
  })
  return { scores, held, first: first && held.length > 0 }
}
