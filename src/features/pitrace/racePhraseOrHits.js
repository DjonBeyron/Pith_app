// Проход 2 «Скажи»: слова, услышанные в ТЕКУЩЕМ заходе, не пропадают из разбора из-за старого текста прошлых заходов (журнал владельца 2026-11-27 13:33:26–13:33:30, «I'm trying to learn»:
// первый заход «trying to learn» (без «I'm», 75 % — не засчитан, «жду исправления»), повтор «i'm», «i'm trying» — разбор по склеенному тексту «trying to learn i'm trying» берёт НАИБОЛЬШУЮ цепочку
// по порядку (старые три слова), «i'm» в неё не входит — слово в сцену не уходило, пилюля молчала, а целиком фраза зажглась, только когда повтор стал длиннее старой цепочки).
// Здесь: разбор по склеенному тексту + разбор одного текущего захода, слово сказано, если сказано хоть в одном (ratio / ok пересчитаны). Чистая функция.
export function orHits(a, b) {
  return a.map(s => {
    const o = b.find(x => x.key === s.key); if (!o) return s
    const hits = s.hits.map((h, i) => h || !!o.hits[i]), ok = hits.filter(Boolean).length
    return ok === s.ok ? s : { ...s, hits, ok, ratio: hits.length ? ok / hits.length : 0 }
  })
}
