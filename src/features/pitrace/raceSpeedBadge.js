// Бейдж скорости «Гонки с Питом» (RaceSpeedBadge.jsx, CONCEPT_RACE.md «Скорость дорожек»): небольшая плашка у верха сцены «×1,1 … ×1,5» — текущий множитель скорости конвейера; появляется на BADGE_MS при каждой смене
// множителя (привод дорожек сообщает его через onSpeed, laneConveyorDrive.js) и гаснет. Скорость 1 (обычный ход) бейдж не показывает. Чистые функции: подпись и решение «показывать».
export const BADGE_MS = 1000

/** Подпись множителя: 1.1 → «×1,1», 1.05 → «×1,05», 1.5 → «×1,5» (запятая, без лишних нулей) */
export const speedLabel = v => `×${String(Math.round(v * 100) / 100).replace('.', ',')}`

/** Показывать ли бейдж для нового множителя v (больше 1: на обычной скорости бейджа нет) */
export const badgeShown = v => Number.isFinite(v) && v > 1.0001
