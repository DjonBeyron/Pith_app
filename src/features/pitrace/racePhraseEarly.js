// Ранний выезд пилюли круга 2 «Скажи» (замечание владельца 3: «Пит произносит задание, и пилюля уже должна успеть выехать к моменту, когда Пит закончит говорить»).
// Раньше ход ждал, пока Пит договорит (fx.pitLeft), и только потом пилюля выезжала из-за верхнего края — до зоны чтения ехала ещё ≈ 5 с. Теперь (racePhraseScene.js, оба прохода) она
// выезжает на событии 'pre' вместе с началом реплики: стартовая точка выбрана так, чтобы к концу реплики (pitMs — сколько Пит будет занят, сразу после fx.pre) центр был у верха зоны чтения
// ZONE_TOP_Y, но не ниже EARLY_MAX_Y (как у демо: выкатывается из-под верхнего затемнения) и не выше ENTER_Y. Реплика короче пути — пилюля просто едет (в зоне чуть позже).
// Единый конвейер не ломается: до едущей впереди пилюли — не меньше пути за cfg.gap; места нет — null (пилюля выедет обычным потоком, когда пройдёт gap).
import { ENTER_Y, SPEED } from '../player/modules/rotate-phone/wordLaneTimeline.js'

export const ZONE_TOP_Y = 22   // верх зоны чтения, % высоты (центр пилюли)
export const EARLY_MAX_Y = 8   // ниже этого пилюля не появляется (верхний край ещё под затемнением)

/** → atMs для pool.take (на сколько мс полёта пилюля уже «проехала») или null — места нет. pitMs — сколько ещё говорит Пит, speed — скорость круга, gap — cfg.gap, ys — центры едущих пилюль */
export function earlyAtMs({ pitMs = 0, speed, gap, ys = [] }) {
  const v = SPEED * speed // % высоты в секунду
  let y = Math.max(ENTER_Y, Math.min(EARLY_MAX_Y, ZONE_TOP_Y - (v * Math.max(0, pitMs)) / 1000))
  const top = ys.length ? Math.min(...ys) : Infinity
  y = Math.min(y, top - (v * gap) / 1000)
  return y < ENTER_Y - 1e-9 ? null : ((y - ENTER_Y) / v) * 1000
}
