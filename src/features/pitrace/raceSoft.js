// Мягкие мотивирующие реплики Пита на СЛАБОМ слове (владелец 2026-11-27: «на 80 % и более нужно несколько реплик — это сигнал, что слово сказано неверно или он его не знает: три разные, мягкие, короткие»).
// Слабое слово — слово РАЗРЕШИЛОСЬ плохо: «не успел» (пилюля ушла: молчание или неверное), «поверил» чужому переводу на ловушке, либо верное слово принято, когда пилюля прошла ≥ LATE_SHARE (80 %) пути
// (racePathShare.js). Неверное слово при живой пилюле НЕ повод: ученик ещё может поправиться, Пит не говорит под руку. Пит иногда говорит одну из SOFT_IDS: не чаще раза на 3 слабых слова (план — goodPlan:
// 3–4 слабых слова между репликами, две подряд не повторяются), только в этапах Пита (проход A и B, softStage): не в «Допросе» и экзамене (там Мия), не во «Фразах». Только если Пит и секвенсор речи свободны (иначе пропуск —
// счёт слабых слов идёт). Чистый модуль без React: состояние — createSoft(seed). Директор (useRaceActs) говорит id и не считает Пита занятым ради следующей пилюли (soft.until).
import { goodPlan } from './raceGood.js'

export const SOFT_IDS = ['race_soft_1', 'race_soft_2', 'race_soft_3']
export const SOFT_PLAN_N = 80 // на сколько слабых слов считается план (дальше реплик нет)

/** Стадия, где Пит говорит мягкие реплики: проход A / B (очередь пилюль), без Мии и без экзамена */
export const softStage = st => !!st && st.type === 'student' && (st.act === 'sprint' || st.act === 'catch') && !st.mia && !st.silent

/** Слабое слово по итогу: not trap — «не успел» всегда слабое; на ловушке слабое только «поверил»; верное при доле ≥ LATE_SHARE — слабое (проверяется отдельно, racePathShare.isLateShare) */
export const failIsWeak = (word, rep) => !word?.trap || !!rep?.believed

/** Состояние одной игры: weak(key) — слово key разрешилось слабо → id реплики или null (нет её в плане / слово уже считали). Одно слово считается один раз */
export function createSoft(seed) {
  const plan = goodPlan(seed ?? 'soft', 'soft', SOFT_PLAN_N, { first: true, ids: SOFT_IDS })
  const seen = new Set()
  let n = 0
  return {
    weak(key) { if (seen.has(key)) return null; seen.add(key); n += 1; return plan.find(g => g.at === n)?.id ?? null },
    count: () => n,
    plan,
  }
}
