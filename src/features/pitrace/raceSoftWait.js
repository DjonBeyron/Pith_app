// Мягкие реплики Пита: КОГДА говорить (владелец 2026-11-27, журнал v3.3.384: «они запускаются слишком рано, они должны быть сказаны, когда пилюля уже полностью скрылась за пределы экрана»).
// В v3.3.384 реплика стартовала в событии слабого слова (claim / fail) — пилюля ещё была на экране. Теперь слабое слово только ЗАПИСЫВАЕТСЯ (arm: план «раз в 3–4 слабых» — raceSoft.js), а реплика звучит
// по событию «пилюля этого слова ушла» (useWordLanePills → wordLaneRepGone → fx.gone): конец улёта вверх (анимация взлёта кончилась и пилюля вернулась в пул), конец ухода за нижний край (give)
// или конец всплытия «Гонки с Питом» (linger). Не по таймеру под старую длину улёта. Пропуск (счёт слабых слов идёт): Пит или секвенсор речи заняты (в т. ч. уже говорит перевод следующего слова);
// следующая пилюля уже на экране (не наезжать на неё и не задерживать её зачёт и выезд); слово устарело (SOFT_STALE_MS). Пауза и смена стадии снимают ожидание (clear): после «Продолжить» реплики нет.
import { createSoft, softStage } from './raceSoft.js'

export const SOFT_STALE_MS = 6000 // слабое слово старше этого — реплика уже не к месту

export function createSoftSay({ seed, log = () => {}, now = () => Date.now() } = {}) {
  const soft = createSoft(seed ?? 'soft')
  let p = null // ожидающая реплика: { sid, idx, id, why, at }
  return {
    /** Слово idx стадии st разрешилось слабо: записать (реплика — когда пилюля уйдёт) */
    arm(st, idx, why) {
      if (!softStage(st)) return
      const id = soft.weak(`${st.sid}:${idx}`); if (!id) return
      if (p) log(`[soft] реплика «${p.id}» слова ${p.idx + 1} снята: слабым стало слово ${idx + 1}, пилюля прежнего не успела уйти`)
      p = { sid: st.sid, idx, id, why, at: now() }
    },
    /** Пилюля слова info.idx ушла полностью (info.out — сколько повторов ещё на экране; busy — Пит / речь заняты) → id реплики, которую сказать сейчас, или null */
    gone(st, info, busy) {
      if (!p || p.sid !== st?.sid || p.idx !== info?.idx) return null
      const w = p, ms = now() - w.at, head = `[soft] слабое слово ${w.idx + 1} (${w.why}): реплика «${w.id}»`; p = null
      if (ms > SOFT_STALE_MS) { log(`${head} пропущена — слово устарело (${ms} мс)`); return null }
      if (info.out > 0) { log(`${head} пропущена — следующая пилюля уже на экране (${info.out})`); return null }
      if (busy) { log(`${head} пропущена — Пит занят`); return null }
      log(`${head} после ухода пилюли (${ms} мс после claim)`)
      return w.id
    },
    /** Пауза / смена стадии / выход: ожидание снято */
    clear(why) { if (p) log(`[soft] реплика «${p.id}» слова ${p.idx + 1} снята: ${why}`); p = null },
    pending: () => p?.id ?? null,
  }
}
