import { IMPACT, ARR } from './miaMotion.js'

// Коробка Мии падает ЗАРАНЕЕ (владелец 2026-11-27: «как только Пит договорил реплику своего этапа — на него уже надета коробка, то есть пока он говорит последнюю реплику, коробка уже летит сверху»).
// Раньше коробка стартовала через 300 мс после КОНЦА реплики и накрывала Пита ещё ≈ 1 с спустя (падение до удара — IMPACT ≈ 0,95 с): тишина ≈ 1,25 с. Теперь удар приходится на конец реплики:
// старт падения = конец реплики − время падения. Нижняя граница — начало реплики (реплика короче падения: коробка стартует с её первым словом и накрывает Пита чуть позже конца). Длина реплики —
// по записи (mspeech.msOf: настоящая длина звука; нет записи — оценка по тексту), числа «под файл» нет. Сроки считаются в мс от входа в стадию («часы коробки», raceMia.at).
export const IMPACT_MS = Math.round(IMPACT * 1000)

/** → { dropAt (мс от входа в стадию до старта падения), jumpAt (с от старта падения до прыжка Мии) }. lineAtMs — когда реплика Пита начинается, lineMs — сколько она звучит, reserveMs — запас (удар чуть раньше конца).
 *  Прыжок Мии стоит там же, где стоял при падении «через 300 мс после конца» (её реплики из-за края идут от конца реплики Пита и не должны сдвинуться): абсолютный срок прежний. */
export function miaDropPlan({ lineAtMs = 0, lineMs = 0, reserveMs = 0, impactMs = IMPACT_MS } = {}) {
  const at = Math.max(0, lineAtMs), len = Math.max(0, lineMs)
  const dropAt = Math.round(Math.max(at, at + len - impactMs - Math.max(0, reserveMs)))
  const oldDropAt = 300 + len // прежнее правило: через 300 мс после конца реплики (при lineAt = 0)
  return { dropAt, jumpAt: Math.max(1, (oldDropAt + ARR.JUMP * 1000 - dropAt) / 1000) }
}
