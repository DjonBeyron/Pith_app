// Момент запуска узора дорожек на старте игры «Встряхни память» (владелец 2026-11-27: «узор нужно запустить, когда Пит говорит о конвейере — «запускаю конвейер слов»»).
// Линии дорожек видны с появления Пита (узор стоит, еле заметный), а ЕХАТЬ он начинает ровно на слове «запускаю» стартовой фразы — в тот же миг, что и плашка этапа (raceOpening.plateAt).
// Срок — от входа в стадию 0 (плашка первого этапа, charge): plateAt − stageAt из расписания открытия; слова в реплике нет — plateAt = начало речи, зажигаем сразу со входа в стадию.
// Привод (laneConveyorDrive) сам разгоняет узор с нуля по мягкой кривой (зажигание 0,5 с + разгон 0,8 с), к первой пилюле он уже на её скорости. Чистая функция.
import { openingPlan } from './raceOpening.js'

/** → мс от входа в стадию st до зажигания узора, null — у этой стадии своё правило (обычная плашка: за 1,3 с до конца сигнала, wordLaneConveyorStart.igniteAtMs) */
export function conveyorLaunchMs(st, plan, lines = null, rate = 1) {
  if (plan?.game !== 'race' || !st?.charge || st.type !== 'announce') return null
  const o = openingPlan(plan, lines, rate)
  return Math.max(0, Math.round((o.plateAt ?? 0) - (o.stageAt ?? 0)))
}
