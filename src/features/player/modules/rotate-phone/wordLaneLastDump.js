// Последняя сессия отладки игры «Повтори за диктором» — для общего журнала плеера (downloadDebugLog.js, раздел «Игра»): владелец присылает текстовый журнал из шапки урока, а не JSON игры,
// и данные игры должны приезжать с любым экспортом. Храним саму сессию (объект в памяти, не копию): dump() вызывается в момент экспорта и отдаёт актуальный журнал — даже если игра уже закрыта
// или ещё идёт. Новая игра заменяет прежнюю. Отдельный маленький модуль, чтобы журнал плеера не тянул за собой хук игры (useWordLaneDebug.js его реэкспортирует).
let lastSession = null

/** Дамп последней игры (то же, что пишется в JSON «Скачать отладку», без аудио) или null: игры не было / отладка была выключена */
export function getLastWordLaneDump() {
  try { return lastSession?.dump() ?? null } catch { return null }
}

/** Запомнить сессию как «последнюю» (зовёт useWordLaneDebug при старте игры); выключенная отладка (NO_DEBUG) и null — забыть */
export function setLastWordLaneSession(session) { lastSession = session?.enabled ? session : null }
