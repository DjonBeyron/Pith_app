// Часы фазы диктора: пилюли и заливка идут по ЗВУКУ, а не по таймеру. Раньше визуал считался от performance.now(), а файл включался отдельным setTimeout — и они расходились:
// у файла своя задержка старта (декодирование на телефоне 100–400 мс), у таймеров дрожь, у урока может стоять скорость голоса ≠ 1 (файл играет быстрее/медленнее, а слова в плане — в секундах
// файла), у эффекта фазы своя точка отсчёта. Теперь, пока файл РЕАЛЬНО играет, время фазы = audioAt + currentTime файла, а таймер только «домысливает» время до старта звука и после его конца.
// Чтобы при подключении звука картинка не прыгала, расхождение (drift) сходится к нулю плавно (экспонента, постоянная TAU_MS), без скачков.
export const TAU_MS = 140
// Картинка никогда не идёт назад и не скачет: поправка за кадр ограничена — вперёд до MAX_UP·dt (хватает на скорость голоса 2×), назад до MAX_DOWN·dt (время всё равно идёт вперёд ≥ 0,1× реального)
export const MAX_UP = 1.2
export const MAX_DOWN = 0.9
// Звук ещё не включился, а по плану уже должен: картинка ДЕРЖИТСЯ на моменте audioAt (пилюля первого слова у центра), а не бежит дальше — иначе при старте звука пришлось бы откатывать её назад.
// Держим не дольше HOLD_MAX_MS: звук так и не пошёл (заблокирован, не загрузился) — картинка продолжает по таймеру
export const HOLD_MAX_MS = 1500

/**
 * Один кадр часов. tTimer — время по таймеру (мс от старта фазы), audioMs — currentTime файла в мс, если файл играет (иначе null), audioAt — когда по плану должен зазвучать файл,
 * drift — накопленное расхождение «звук минус таймер», prev — расхождение, замеренное в прошлом кадре (null — звук только что включился), dt — мс с прошлого кадра.
 * Поправка складывается из двух частей: опережение (feed-forward — картинка сразу берёт реальную скорость звука, поэтому скорость голоса 0,75× или 2× не даёт отставания) и сглаженная
 * коррекция остатка (экспонента TAU_MS). wait — звук ожидается, но ещё не пошёл (картинка ждёт его на audioAt, см. HOLD_MAX_MS). Возвращает { t, drift, prev }: t — время фазы для картинки.
 */
export function syncClock({ tTimer, audioMs = null, audioAt = 0, drift = 0, prev = null, dt = 16, wait = false }) {
  if (audioMs == null) {
    // wait — звук ожидается (есть озвучка автора, но она ещё не зазвучала): время не уходит за audioAt
    if (wait && tTimer + drift >= audioAt && tTimer < audioAt + HOLD_MAX_MS) return { t: audioAt, drift: audioAt - tTimer, prev: null }
    return { t: tTimer + drift, drift, prev: null }
  }
  const target = audioAt + audioMs - tTimer
  const k = 1 - Math.exp(-Math.max(0, dt) / TAU_MS)
  const ahead = prev == null ? 0 : target - prev           // как изменилось расхождение за кадр — картинка повторяет это сразу
  const fix = (target - (drift + ahead)) * k               // а остаток подтягиваем плавно
  const step = Math.min(MAX_UP * dt, Math.max(-MAX_DOWN * dt, ahead + fix))
  const next = drift + step
  return { t: tTimer + next, drift: next, prev: target }
}

/** Файл играет по-настоящему: элемент есть, не на паузе, не закончился и время пошло */
export function audioPlayingMs(el) {
  if (!el || el.paused || el.ended) return null
  const ms = el.currentTime * 1000
  return ms > 0 ? ms : null
}
