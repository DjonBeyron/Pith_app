import { pLog } from '../../../../shared/lib/debug.js'

// ОДНА очередь речи Пита (v3.3.113, замечание владельца «Пит дёргается вверх-вниз, будто две реплики одновременно»). Причина: каждый элемент речи — реплика успеха, русский перевод, английское слово, подсказка —
// сам вызывал peek.hold(ms + 400) и сам решал, когда голове прятаться. Между двумя соседними элементами (реплика кончилась → пауза LINE_PAUSE_MS 600 мс → перевод) голова «не нужна» дольше 400 мс: она начинала
// опускаться (0,42 с), и следующий элемент её тут же поднимал снова — рывок вниз-вверх на каждом принятом слове. Теперь все элементы встают в одну очередь:
//  • add(kind, ms, meta) — элемент речи (реплика / перевод / слово) начинается СЕЙЧАС и длится ms: голова нужна до конца элемента + хвост QUEUE_TAIL_MS (дольше самой длинной паузы между элементами, 600 мс), поэтому
//    между элементами очереди она не прячется. Голова выскакивает один раз на всю очередь и прячется через QUEUE_TAIL_MS после последнего элемента;
//  • touch(ms) — «ещё нужна»: только ПРОДЛЕВАЕТ (реакция лицом, просто выскочить), анимацию не перезапускает: peek.hold при поднятой голове лишь двигает срок, поднятие и уход — по одному разу;
//  • reset() — игра закрыта / пауза: очередь пуста.
// Если новый элемент начался, пока предыдущий ещё звучит (наложение — не должно быть: Пит занят, wordLaneCatLines), в журнал уходит «НАЛОЖЕНИЕ». Журнал: «[cat] очередь: …». Чистый модуль: часы, таймеры и журнал приходят аргументами.
export const QUEUE_TAIL_MS = 900 // голова остаётся наверху столько мс после конца последнего элемента (длиннее паузы между репликами, LINE_PAUSE_MS = 600)

export function createCatQueue({ peek, now = () => performance.now(), setTimer = setTimeout, clearTimer = clearTimeout, log = pLog }) {
  let tail = 0         // до какого момента (now) звучит последний элемент
  let items = 0        // сколько элементов ещё звучит
  let lifts = 0        // сколько раз очередь подняла голову (диагностика, тесты)
  const timers = new Set()

  const raise = ms => { const was = peek.isUp(); peek.hold(ms); if (!was && peek.isUp()) lifts += 1; return !was }

  return {
    /** Элемент речи начался: kind — 'реплика' | 'перевод' | 'слово', ms — сколько он длится, meta.id — какая реплика / слово */
    add(kind, ms, meta = null) {
      const t = now(), len = Math.max(0, ms)
      const overlap = items > 0 && t < tail - 120
      const up = raise(len + QUEUE_TAIL_MS)
      items += 1
      tail = Math.max(tail, t + len)
      const id = setTimer(() => { timers.delete(id); items = Math.max(0, items - 1); if (items === 0) log('[cat] очередь: пуста, голова уйдёт через ' + QUEUE_TAIL_MS + ' мс') }, len)
      timers.add(id)
      log(`[cat] очередь: +${kind}${meta?.id ? ` «${meta.id}»` : ''} ${Math.round(len)} мс, в очереди ${items}, ${up ? 'голова поднимается' : 'голова уже наверху (не перезапускаю)'}${overlap ? ', НАЛОЖЕНИЕ: предыдущий элемент ещё звучит' : ''}`)
    },
    /** Голова нужна ещё ms (реакция лицом, «выскочить»): срок только продлевается */
    touch(ms) { raise(ms) },
    /** Сколько мс звучит последний элемент (0 — очередь пуста) */
    busyLeft: () => Math.max(0, tail - now()),
    size: () => items,
    stats: () => ({ items, lifts }),
    reset() { timers.forEach(clearTimer); timers.clear(); items = 0; tail = 0 },
  }
}
