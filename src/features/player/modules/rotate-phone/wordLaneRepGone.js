// «Пилюля слова полностью ушла за пределы экрана» (владелец 2026-11-27: мягкие реплики Пита — когда пилюля уже скрылась): событие движка пилюль для режиссёра гонки (fx.gone({ idx, why, out })).
// Три конца: 'rise' — взлёт принятой пилюли кончился (анимация закончена, пилюля вернулась в пул: простой улёт ≈ 300–400 мс, обычный 180 + 750 мс), 'fail' — упущенная пилюля ушла за нижний край
// (give в кадре движка; у повтора из нескольких кусков — когда ушёл последний), 'linger' — всплывшая упущенная пилюля «Гонки с Питом» погасла. Ни таймеров, ни своей анимации: слушаем конец уже идущей;
// отменённая анимация (пауза, смена стадии, giveAll) события не даёт. out — сколько повторов ещё держит движок на экране (следующая пилюля уже выехала).
export function createRepGone(held, fxRef) {
  const repOf = new Map() // id пилюли → номер повтора (пока пилюля у движка или летит вверх)
  const out = () => new Set([...held.keys()].map(id => repOf.get(id))).size
  const fire = (idx, why) => fxRef.current?.gone?.({ idx, why, out: out() })
  const left = idx => [...repOf.values()].includes(idx)
  return {
    spawn: (id, idx) => repOf.set(id, idx),
    /** Принятая пилюля взлетает (анимация a): событие — когда взлёт кончился; last === false — не последний кусок повтора */
    rose(id, idx, a, last = true) { repOf.delete(id); if (last) a?.finished?.then(() => fire(idx, 'rise')).catch(() => { /* снята раньше: пауза, смена стадии */ }) },
    /** Пилюля ушла за нижний край (движок вернул её в пул) */
    below(id) { const idx = repOf.get(id); repOf.delete(id); if (idx != null && !left(idx)) fire(idx, 'fail') },
    /** Упущенная пилюля всплыла и держится (linger, анимация a): событие — когда погасла */
    lingered(id, idx, a) { repOf.delete(id); if (!left(idx)) a?.finished?.then(() => fire(idx, 'linger')).catch(() => { /* снята раньше */ }) },
  }
}
