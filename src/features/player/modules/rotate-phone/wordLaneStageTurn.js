import { pLog } from '../../../../shared/lib/debug.js'

// Отложенный переход стадии «дальше» действует, только пока идёт ТА ЖЕ стадия, что его поставила (журнал владельца 2026-11-25, iPhone: попап «Комментарий к логам» открыт, игра на паузе, а через
// 41 с Мия ушла, конвейер развернулся и пошёл проход B — игра сама снялась с паузы без «Продолжить», микрофон уже был отпущен → «Не получается слушать»).
// Причина: стадия-плашка отдаёт переход очереди rh.afterCount (отсчёт нот, конец речи Мии, «коробку сняли» — pitrace/mia, pitrace/boss). Эти очереди живут на СВОИХ таймерах и опросах: пауза (useWordLaneControls.pause)
// их не снимает, и опоздавший вызов делал go('run', i) прямо из паузы. Теперь переход сверяет стадию: пауза (stage 'paused'), «Продолжить» / перезапуск ступени (новая отметка at) и смена стадии делают его пустым.
// Так же устроен переход после ступени ученика (useWordLaneFlow → handlers.finished).
export const PAUSED_NEXT_LOG = '[pause] переход стадии отклонён: игра на паузе — дальше только по «Продолжить»'

/** Идёт ли ещё стадия (idx, at): cur — текущее состояние директора { stage, idx, at } */
export const stageStill = (cur, idx, at) => cur?.stage === 'run' && cur.idx === idx && cur.at === at

/** Переход для стадии (idx, at): next() — только пока она идёт; иначе строка в журнал (кто опоздал — видно по соседним строкам) и ничего. sRef — ref состояния директора */
export function stageTurn(sRef, idx, at, next, log = pLog) {
  return () => {
    const cur = sRef.current
    if (stageStill(cur, idx, at)) { next(); return }
    log(`[pause] опоздавший переход стадии ${idx} отброшен: сейчас ${cur?.stage === 'paused' ? 'пауза' : `стадия ${cur?.stage}/${cur?.idx}`} — игра не двигается`)
  }
}
