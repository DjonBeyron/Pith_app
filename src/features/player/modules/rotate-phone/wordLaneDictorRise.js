// Взлёт пилюль диктора (Пит) после примера: когда повтор договорён, ВСЕ его пилюли улетают вверх тем же взлётом, что у ученика после верного ответа (pool.rise → wordLaneRise.js / wordLaneWave.js), и дорожка каждой пилюли
// вспыхивает (pool.flashLane → wordLaneLaneFlash.js); искры и хлопок даёт snapPill в момент слова (wordLaneSnap.js). Реакции на Пита и на ученика одинаковые; награды (нота, XP, кот) диктору не положены — только картинка.
// Время взлёта (RISE_DELAY_MS + RISE_MS) входит в длительность ступени диктора (wordLaneDictor.DICTOR_RISE_MS), поэтому раунд ученика начинается после взлёта, а не посреди него.
// held — список { p (пилюля плана), k (номер в пуле или null) } из движка пилюль; взлетевшей пилюле k = null: пул вернёт её сам, когда взлёт кончится, и кадровая заливка её больше не трогает (иначе чужая пилюля получила бы чужую заливку).
/** Пилюли повтора rep взлетают. → сколько пилюль взлетело */
export function riseRep(pool, held, rep) {
  let n = 0
  for (const h of held) {
    if (h.k == null || h.p.rep !== rep) continue
    pool.flashLane(h.p.lane)
    if (pool.rise(h.k)) { h.k = null; n += 1 }
  }
  return n
}
