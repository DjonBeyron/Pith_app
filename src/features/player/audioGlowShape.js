// Форма столбиков свечения-эквалайзера (AudioGlow.jsx) — чистая математика,
// отдельно от компонента (react-refresh не любит не-компонентные экспорты в .jsx).
//
// Каждому столбику — своя форма: сумма двух синусов с разной частотой/фазой
// (дешёвая псевдослучайность по индексу) даёт спектр, а не один блок; крайние
// столбики ниже средних, как у настоящего спектра речи. Один цвет у всех —
// фиолетовый, меняется только высота (scaleY).
export const BAR_COUNT = 16

export const BARS = Array.from({ length: BAR_COUNT }, (_, i) => ({
  f1: 3.1 + ((i * 37) % 11) * 0.47,
  f2: 0.9 + ((i * 53) % 7) * 0.31,
  p:  (i * 2.399) % 6.283,
  edge: 0.55 + 0.45 * Math.sin(Math.PI * (i + 0.5) / BAR_COUNT),
}))

// Высота столбика i (0..1) при уровне речи level (0..1) в момент t (секунды):
// v = level × (0.45 + 0.55·shape_i(t)) × edge_i, не ниже 0.02 (тонкая ножка)
export function barHeight(i, level, t) {
  const b = BARS[i]
  const shape = 0.5 + 0.35 * Math.sin(t * b.f1 + b.p) + 0.15 * Math.sin(t * b.f2 + b.p * 2)
  return Math.max(0.02, level * (0.45 + 0.55 * shape) * b.edge)
}
