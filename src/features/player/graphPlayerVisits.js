// Повторный показ одной и той же ноды: сценарий бывает цикличным —
// «ошибся → подсказка → снова тот же вопрос». Чистые функции для
// useGraphPlayer.js, чтобы это поведение можно было проверить тестами.

// Нода снова становится ПОСЛЕДНЕЙ в ленте, а не игнорируется как «уже
// показанная». Без этого панель ответа не открывалась второй раз: она живёт
// только у последней ноды (usePlayerPanelNodes.js) — таблица после разбора
// ошибки просто не запускалась.
//
// visit — номер показа: он уходит в ключ панели (PlayerPanels.jsx), чтобы та
// пересобралась с чистого листа, а не осталась с разбором прошлой попытки.
export function appendVisit(visible, node, visit) {
  return [...visible.filter(n => n.id !== node.id), { ...node, visit }]
}

// Триггеры показанной заново ноды должны срабатывать снова: дедуп firedRef
// защищает от двойных переходов внутри ОДНОГО показа, а не на весь урок.
// Иначе после первого «неверно» второй заход в ту же таблицу уже никуда не
// вёл — цепочка вставала намертво.
export function forgetNodeKeys(fired, nodeId) {
  const next = new Set(fired)
  for (const key of fired) {
    if (key.startsWith(`${nodeId}:`)) next.delete(key)
  }
  return next
}
