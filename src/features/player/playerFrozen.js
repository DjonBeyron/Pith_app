import { createContext, useContext } from 'react'

// «Заморозка» шагового режима (админ, запуск из канваса): текущее сообщение
// не звучит и не печатается.
//
// Это НЕ то же самое, что пауза цепочки. Пауза держит переходы, а заморозка —
// проигрывание конкретного сообщения: шаг «вперёд» снимает заморозку, чтобы
// новое сообщение отыгралось целиком (у голосового текст печатается синхронно
// со звуком — на заглушённом аудио он не появился бы вовсе), но следующая
// нода всё равно ждёт кнопки.
//
// Контекст, а не проп: заморозку должны видеть модули глубоко внутри ленты
// (печать текста, заглушка нод без медиа), а тащить флаг через PlayerMessage
// в каждый из 14 типов — правка в четырнадцати файлах ради одного булева.
// В обычном плеере контекст всегда false.
export const PlayerFrozenContext = createContext(false)

export function usePlayerFrozen() {
  return useContext(PlayerFrozenContext)
}
