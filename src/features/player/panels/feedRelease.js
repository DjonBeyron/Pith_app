// Сдвиг переписки трансформом вместо пересчёта раскладки.
//
// Место под панель ответа держит распорка (spacerStyle.js). Когда панель
// уходит, место надо вернуть — и вот тут важно КАК. Анимировать height самой
// распорки нельзя: это layout, он пересчитывается каждый кадр, и при высокой
// панели над длинной перепиской на телефоне это читается как торможение,
// даже когда цифры в трассе ровные.
//
// Поэтому высота снимается РАЗОМ (раскладка сразу конечная), а видимый скачок
// гасится трансформом на .playerFeedInner, который затем плавно уводится в
// ноль. Трансформ композитится на GPU — тем же конвейером, что и уход панели.
//
// Лента перевёрнута через scaleY(-1) (см. feed.css), поэтому переворот
// сохраняется в каждом кадре анимации — иначе она встанет с ног на голову.
//
// Раньше этот приём жил внутри useTableToChat и работал только на уходе
// таблицы в чат. Обычное закрытие панели шло через height-анимацию и лагало
// именно на высоких панелях: у ручной таблицы со списком слов — 297px.
const DURATION = 320
// Мягкий старт обязателен: движение начинается из покоя, а easeOut-кривые
// срываются с места на полной скорости — первый же кадр давал 17px и читался
// рывком. Те же цифры у превращения клона (FLIGHT_MS/SPACER_EASE)
const EASING = 'cubic-bezier(0.4, 0, 0.2, 1)'

// drop — на сколько переписка УЖЕ сместилась к этому моменту.
// Знак любой: плюс — уехала вниз, минус — вверх.
//
// duration/easing переопределяются намеренно. Переписка и панель едут вниз
// ОДНОВРЕМЕННО, и глазу видно не то, что они стартуют вместе, а то, что они
// идут по-разному: у панели ease-in (разгон), у ленты по умолчанию
// ease-in-out (разгон и торможение). Замер по кадрам показывал это в лоб —
// панель +7 +18 +26 +31 +38, лента +8 +31 +68 +76 +51. Чтобы движение
// читалось одним, вызывающий передаёт сюда СВОИ кривую и длительность.
export function playFeedRelease(drop, { duration = DURATION, easing = EASING } = {}) {
  const inner = document.querySelector('.playerFeedInner')
  if (!inner) return
  if (Math.abs(drop) < 1) { inner.style.transform = ''; return }
  // Первый кадр анимации сам удержит историю на месте — отдельная
  // предустановка стиля не нужна и только создала бы лишний кадр
  const anim = inner.animate(
    [
      { transform: `scaleY(-1) translateY(${-drop}px)` },
      { transform: 'scaleY(-1) translateY(0px)' },
    ],
    { duration, easing },
  )
  const clear = () => { inner.style.transform = '' }
  anim.onfinish = clear
  anim.oncancel = clear
}
