// Ждёт, пока последнее сообщение переписки закончит въезжать, и только потом
// зовёт продолжение.
//
// Зачем: пузырь с ответом не просто появляется — PlayerFeed играет ему
// slide-in из-под нижнего края экрана (MSG_SLIDE_MS). Если панель тронуть в
// это время, на один пузырь ложатся два встречных движения: он ещё едет
// вверх, а лента уже опускает его вниз. По кадрам это видно как единственный
// сбойный кадр в начале: Δпанель=+7, Δответ=−21.
//
// Фиксированная задержка тут не годится — она то попадает, то нет (в замерах
// один прогон давал расхождение 0, следующий 28): анимацию запускает эффект
// PlayerFeed, и момент её старта плавает. Спрашиваем у самих анимаций.
const LIMIT_MS = 900

export function whenBubbleLanded(next) {
  const row = [...document.querySelectorAll('.playerMsgRowRight')].pop()
  const anims = row ? row.getAnimations({ subtree: true }) : []
  if (!anims.length) { next(); return }
  // Страховка: если анимация почему-то не завершится (её отменили, элемент
  // сняли), продолжение всё равно должно случиться — панель не может остаться
  // на экране навсегда
  let done = false
  const go = () => { if (!done) { done = true; next() } }
  const timer = setTimeout(go, LIMIT_MS)
  Promise.allSettled(anims.map(a => a.finished)).then(() => { clearTimeout(timer); go() })
}
