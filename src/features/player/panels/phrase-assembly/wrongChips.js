// Красная подсветка после неверной «Проверить» в «Собери фразу» — только чипы, которые стояли
// в ответе В МОМЕНТ проверки. Раньше красный флаг жил на результате целиком (result === 'wrong'),
// и слово, добавленное сразу после проверки, оказывалось под тем же флагом.
// Снимок — id чипов банка (shuffleIdx, уникален и не сдвигается при снятии слова из середины),
// а не позиции в строке ответа.

// Снимок на момент проверки: какие чипы стояли в ответе
export function snapshotWrongIds(placed) {
  return placed.map(p => p.shuffleIdx)
}

// Для каждого слова строки ответа — красное ли оно. Без снимка (нет неверной проверки / окно
// красного истекло / ответ менялся) красных нет; слово, которого не было в снимке — не красное.
export function wrongChipFlags(placed, snapshot) {
  if (!snapshot || snapshot.length === 0) return placed.map(() => false)
  const ids = new Set(snapshot)
  return placed.map(p => ids.has(p.shuffleIdx))
}
