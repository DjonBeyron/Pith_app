// Стиль распорки под лентой — общий для таблицы в авто- и ручном режиме.
//
// Распорка открывается БЫСТРЕЕ панели и по более резкой кривой (0.26s против
// 0.38s у .tdPanel/.tmPanel). Это не украшательство: панель едет transform'ом
// на своём композитном слое, а распорка меняет height, то есть layout —
// разные конвейеры, и при формально одинаковых кривых панель на экране
// опережает освобождение места. Замер вживую: панель уже на 434, а лента
// заканчивалась на 577 — нижние 143px последнего сообщения оказывались под
// панелью. Пусть место освобождается с запасом, тогда перекрытия нет ни в
// один кадр.
//
// Особый случай — уход таблицы в чат, там движение идёт в два приёма:
//
//  1. Вставка пузыря толкает ленту ВВЕРХ на его высоту (FLIP в PlayerFeed).
//     Распорка в тот же React-батч отдаёт ровно столько же и БЕЗ перехода —
//     один пересчёт layout, и лента не двигается вообще. Раньше эти два
//     движения шли врозь, с разными кривыми: история подпрыгивала, потом
//     сползала.
//  2. Остаток (высота панели минус пузырь) держится до посадки и только потом
//     уходит в ноль. Пока идёт превращение, история неподвижна и вверх едет
//     ТАБЛИЦА — движение читается как «таблица уходит в переписку», а не как
//     «переписка съезжает к таблице». Место панели освобождается следом.
const OPEN  = 'height 0.26s cubic-bezier(0.16, 1, 0.3, 1)'
// Обычное закрытие: панель уезжает вниз, разгоняясь — ей ease-in идёт
const CLOSE = 'height 0.22s cubic-bezier(0.4, 0, 1, 1)'
// Отдача места после превращения идёт БЕЗ перехода: высота снимается разом, а
// сам сдвиг истории проигрывает трансформ на .playerFeedInner (см.
// useTableToChat.releaseSpacer). Анимировать здесь height нельзя — это layout,
// он пересчитывается каждый кадр и на экране даёт рывок, даже когда цифры в
// трассе ровные
const RELEASE = 'none'

export function spacerStyle({ show, panelH, givenToBubble, released }) {
  if (givenToBubble != null) {
    return released
      ? { height: 0, transition: RELEASE }
      : { height: Math.max(0, panelH - givenToBubble), transition: 'none' }
  }
  return {
    height: show ? panelH : 0,
    transition: show ? OPEN : CLOSE,
  }
}
