// Зум холста колесом. Смысл в одном: точка под курсором должна остаться под
// курсором — тогда видно, куда «едет» холст, и можно наводиться на нужный
// кусок графа, а не искать его после каждого щелчка колеса.

// Нижняя граница подобрана так, чтобы длинный урок (76 нод, ~27000px по x)
// целиком помещался в экран — иначе групповое выделение рамкой упирается
// в то, что «всё сразу» просто не видно
export const MIN_SCALE = 0.05
export const MAX_SCALE = 2.5

// Ниже этого масштаба текст в нодах всё равно не читается: содержимое нод
// не отрисовывается, у связей убирается «ореол», а слой точек портов не
// рисуется вовсе. Это и есть плата за дальний зум — иначе на каждый щелчок
// колеса браузер перерисовывал бы весь текст графа в нечитаемую кашу.
// Порог ниже прежней границы зума (0.25) — привычный диапазон не меняется
export const FAR_ZOOM = 0.22

// Колесо шлёт дельту в разных единицах — приводим к пикселям
const PX_PER_LINE = 16
const PX_PER_PAGE = 400

// Подобрано так, чтобы один щелчок мыши (deltaY ≈ 100) давал привычные ~10%,
// а мелкие дельты трекпада — плавные доли процента вместо тех же 10% на
// каждое из десятков событий (именно от этого зум и казался рваным)
const SENSITIVITY = 0.0011
// Пинч двумя пальцами приходит как ctrl+wheel с мелкой дельтой — иначе
// щипок почти не двигал бы масштаб
const PINCH_BOOST = 2.5
// Потолок на одно событие: резкий флик колеса или deltaMode=page не должны
// перебрасывать масштаб через весь диапазон разом
const MAX_STEP = 0.25

export function clampScale(s) {
  return Math.min(MAX_SCALE, Math.max(MIN_SCALE, s))
}

// Во сколько раз меняем масштаб на это событие колеса
export function wheelZoomFactor(e) {
  let px = e.deltaY
  if (e.deltaMode === 1) px *= PX_PER_LINE
  else if (e.deltaMode === 2) px *= PX_PER_PAGE
  const k = SENSITIVITY * (e.ctrlKey ? PINCH_BOOST : 1)
  const step = Math.min(MAX_STEP, Math.max(-MAX_STEP, -px * k))
  return Math.exp(step)
}

// Новое смещение холста, при котором точка (px, py) — координаты курсора
// ОТНОСИТЕЛЬНО доски — остаётся ровно там же, где была до смены масштаба
export function zoomAtPoint(offset, cur, next, px, py) {
  const k = next / cur
  return {
    x: px - k * (px - offset.x),
    y: py - k * (py - offset.y),
  }
}
