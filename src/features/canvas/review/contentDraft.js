// Копия урока «по содержанию» для окна разбора: пока ноду только двигают по холсту (x, y, size), содержимое то же — лента, линтер,
// расшифровка и здоровье файлов не пересчитываются (холст шлёт копию каждые 60 мс, пересчёт на 271 ноде — ~30 мс + перерисовка ленты)
const KEYS = ['id', 'seq', 'type', 'typeData', 'triggers', 'note']

/** Те же ноды по содержимому (по ссылкам полей — холст не клонирует нетронутые ноды) */
export const sameContent = (a, b) => a === b || (a.length === b.length && a.every((n, i) => n === b[i] || KEYS.every(k => n[k] === b[i][k])))
