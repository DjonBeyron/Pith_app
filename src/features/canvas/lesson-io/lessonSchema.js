// Легенда формата обмена уроком: что означает каждый тип ноды, каждое поле и
// каждое условие перехода. Она уезжает вместе с экспортом (см. exportLesson.js),
// чтобы урок можно было отдать человеку или модели «как есть» — без доступа к
// коду редактора — и получить обратно готовый шаблон в том же формате.
//
// Файлы (аудио/видео/фото) в обмен НЕ попадают: вместо них в ноде стоит
// пометка needs — какой файл нужно подложить в редакторе после импорта.
//
// Про стороны пузырей: у интерактивных нод responseCorrect рисуется СПРАВА —
// это речь ученика, а не учителя (см. AnswerBubbles.jsx / WordChoiceModule.jsx).
// Реплику учителя туда писать нельзя: получится, что ученик отвечает сам себе.
//
// Про формулировки заданий: ученик не говорит вслух, а собирает фразу из
// слов — поэтому «Скажи ...» вводит в заблуждение. Но и «как бы ты сказал»
// не годится: это прошедшее время второго лица, оно выдаёт мужчину (см. ниже
// про род). Безродные формы: «Как сказать по-английски ...», «Собери фразу
// ...», «Как это будет по-английски ...».
//
// Про повторы: после верного ответа собранная фраза уже висит в переписке
// справа. Повторять её текстом не надо — на неё ставится нода reaction
// (эмодзи), а если нужен разбор, следующая нода даёт только перевод.
//
// Про реакцию на верный ответ: это имитация живой переписки, а не отчёт.
// Сухое «Перевод: ...» звучит по-канцелярски — пишите так, как написал бы
// живой учитель: «я и не сомневался, что справишься — это значит ...».
// Такие реплики ВСЕГДА тип text, не audio: в чате на удачный ответ
// отвечают быстрым сообщением, а не голосовым.
//
// Про живость реплик: писать надо так, как пишут в мессенджере, а не так, как
// формулирует модель. Признаки синтетичности, которых быть не должно:
//   ✗ «Схватываешь на лету 😄 И собрал без таблицы — он пробует пиццу»
//     — две мысли в одной реплике плюс отчёт о том, что и так видно;
//     ✓ «Без таблицы справился 🔥»
//   ✗ «Сейчас запишу фразу голосом — попробуй расслышать её»
//     — так не говорят; ✓ «Слушай, вот фраза целиком»
//   ✗ «О, узнаю 👌» — непонятно, что именно узнают и почему это похвала.
// Реакция должна быть очевидна из контекста: если по ней непонятно, за что
// она, — она лишняя. Короче и проще почти всегда лучше.
//
// Про длину текста: длинный текст — это ВСЕГДА голосовое. Тип text в чате
// читается глазами, и простыня из трёх предложений выглядит как инструкция, а
// не как сообщение от учителя. Ориентир — примерно 120 знаков, одна-две
// короткие фразы. Всё, что длиннее, решается одним из двух способов:
//   · сократить до сути — обычно половина такого текста это разжёвывание;
//   · сделать нодой audio, где длина естественна: голос слушают, а не читают.
// Промежуточного варианта «оставим длинным текстом» нет.
//
// Про переносы строк: у text есть hardWrap — включайте его везде, где текст
// перечисляет или подытоживает. Сводка, разложенная по строкам, читается
// одним взглядом, а та же сводка в строку — сплошная лента, которую надо
// разбирать. Правило простое: каждая пара «форма — что значит», каждый пункт
// итога и каждое противопоставление живут на своей строке.
//   ✗ «Подытожим: I, you, we, they → try. He, she, it → tries»
//   ✓ «Подытожим:⏎ I, you, we, they → try⏎ he, she, it → tries»
// Это не украшательство: без переносов текст растёт в длину, а по правилу
// выше длинный текст обязан стать голосовым — то есть перестать быть тем,
// на что можно взглянуть и вспомнить.
//
// Про подсказки заданием: таблица, открытая рядом с формулировкой, часто
// решает задание за ученика. Если в тексте уже сказано «а теперь это его
// привычка, так каждое утро» — время названо словами, и таблица времён рядом
// оставляет только списать нужную клетку. Показывайте таблицу там, где
// разбираете правило, и убирайте её там, где проверяете, усвоено ли оно.
//
// Про счётные похвалы: «три из трёх», «все верно», «ни одной ошибки» — это
// утверждение о ПУТИ, а граф о пути не знает. Такая реплика должна быть
// достижима ТОЛЬКО по ветке, где все ответы были верными: ветки ошибок ведут
// в свою копию оставшихся заданий и заканчиваются нейтральной репликой. Если
// разводить ветки не хочется — не считайте вслух: «вся группа разобрана»
// верно при любом пути.
//
// Про род: пол ученика неизвестен. Формы «заметил», «справился», «молодец»
// выдают мужчину, а «заметил(а)» — это канцелярит, живой человек так не пишет.
// Нужны формулировки, которые работают для любого:
//   ✗ заметил / собрал / справился / был внимателен
//   ✓ видишь разницу? / получилось / вышло / точно / в точку / то что нужно
// Проще всего уходить от глаголов прошедшего времени в первом-втором лице:
// «получилось» и «вышло» безродные, «ты справился» — нет.
// То же касается речи учителя о себе: учителя в уроке зовут по-разному, и
// «я и не сомневался» так же выдаёт мужчину. Пишите «так и знал(и) бы» — нет,
// пишите без прошедшего времени вовсе: «ну конечно», «а как иначе».
//
// Про раскраску: ВСЁ, что выделено цветом, выделяется и жирностью — это два
// отдельных highlight на один и тот же диапазон (mode: 'text' + mode: 'bold').
// Касается и зелёных английских слов, и белых русских: белым помечается
// смысловое ядро фразы (перевод, само задание), и на фоне серого текста по
// умолчанию одного цвета мало — разница в яркости читается как «чуть светлее»,
// а не как акцент. Подчёркнутое белое — тоже жирное и тоже белое: одного
// mode: 'underline' мало, подчёркивание без цвета и веса не читается.
// Правило действует и в служебных фразах вроде «переведи: ...», и в самих
// переводах. Исключений нет: одно пропущенное bold сразу видно, потому что
// слово рядом с таким же выглядит бледнее.
//
// Про расположение нод: pos — это точка на холсте редактора, и ноды не должны
// ни совпадать, ни налезать друг на друга. Карточка занимает заметное место,
// поэтому:
//   · главная линия урока — один ряд слева направо с шагом около 400;
//   · каждая побочная ветка (разбор ошибки, вторая дорожка) — СВОЙ ряд ниже,
//     ряды с шагом около 420 по вертикали;
//   · внутри ветки ноды идут тем же шагом 400, а не жмутся к родителю.
// Ветки из разных концов урока могут делить один ряд, если их диапазоны x не
// пересекаются. Проверять это надо явно: сложить все pos в набор и убедиться,
// что нет ни одной пары ближе 200 по x при разнице меньше 80 по y. Куча нод
// на холсте не ломает урок в плеере, но делает его неправимым руками.
//
// Где раскраска НЕ работает: responseCorrect, responseWrong и system.content
// плеер рисует обычным текстом (AnswerBubbles.jsx, SystemModule.jsx) — поля
// highlights у них нет вовсе. Английские примеры, которые нужно подсветить,
// в подсказку об ошибке класть бесполезно: выносите их следующей нодой text.
//
// Про таблицы, уходящие в чат: если у table стоит sendToChat, ей НУЖНА
// подпись chatCaption — короткое название вроде «Прошедшее время: tried».
// Иначе в переписке остаётся карточка без заголовка, и через десять сообщений
// уже не понять, о чём она. Исключение одно: когда у таблицы есть answer,
// в том же боксе стоит собранная фраза — она и служит подписью, подпись
// затёрла бы её.
//
// Про таймлайн диктанта: как только у таблицы появляется ХОТЬ ОДИН слой с
// cellId, плеер включает гейтинг текста (computeRevealedCellIds) — каждая
// ячейка, которой в таймлайне нет, рисуется ПУСТОЙ. Поэтому в таймлайне
// обязаны быть все ячейки таблицы, включая заголовки и те, что в этой фразе
// не участвуют: им ставится слой на всю длину с highlightOn: false — он
// ничего не подсвечивает, только держит текст видимым.
//
// Про разнообразие реакций: на верный и неверный ответ реагируют РАЗНЫЕ
// средства, и их надо чередовать, а не ставить одно и то же подряд:
//   · reaction — эмодзи прямо на пузыре ответа, самая лёгкая форма;
//   · text с эмодзи — короткая реплика учителя;
//   · sticker — картинка/видео, самая сильная форма, для узловых моментов.
// Два одинаковых средства подряд читаются как автоответчик. Сильные средства
// (стикер) — редко, иначе они перестают что-либо значить.
//
// Про восприятие на слух: в каждом смысловом блоке урока должно быть задание,
// где фраза приходит ТОЛЬКО голосом — собрать её из слов или выбрать из
// предложенных, не видя написанного. Без этого урок тренирует чтение, а не
// понимание речи.

