// Уборка дорожек таймлайна, у которых больше нет своей ячейки.
//
// Ячейка исчезает не только при удалении строки/колонки: объединение делает
// из нескольких ячеек одну новую (новый id), разбиение — наоборот, а
// применение шаблона заменяет всю сетку целиком. Дорожки от старых ячеек
// после этого висят мёртвым грузом: в списке слоёв они помечены «⚠ удали»,
// а в уроке подсвечивать им нечего.
//
// Чистим прямо в конструкторе, на каждую правку сетки — чтобы автору не
// приходилось заходить в таймлайн ради того, чтобы мусор убрался сам.
// Дорожки слов вне таблицы, «Проверить» и «Очистить» не трогаем: у них нет
// ячейки, и живут они по своим правилам (их чистит уборка по тексту ответа).
export function pruneTimelineForCells(timeline, cellIds) {
  const layers = timeline?.layers
  if (!layers?.length) return timeline
  const next = layers.filter(l => !l.cellId || cellIds.has(l.cellId))
  return next.length === layers.length ? timeline : { ...timeline, layers: next }
}
