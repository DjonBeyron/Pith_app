// Что рисует слайд ленты на месте фразы. Вынесено из FeedSlide.jsx ради регрессионного теста: в v3.2.1873 порядок веток
// поменяли на «revealed → обычная фраза», а PhraseBubbleSpoiler зовёт onUnlock (→ revealed) в первом же кадре взрыва — спойлер
// размонтировался, не успев нарисовать ни одной частицы, и «выстрелы» шариков в ленте пропали.
//   'plain'   — фраза открыта и шариков нет (после задания «Ловли слов» или без спойлера);
//   'chip'    — на слайде задание «Ловли слов», фраза ещё закрыта: чип вместо шариков;
//   'spoiler' — обычный слайд: шарики; ОСТАЁТСЯ смонтированным и после тапа (revealed) — он сам доигрывает взрыв и
//               убирает холсты, а открытый текст показывает внутри себя.
export function phraseSurface({ ctActive, revealed }) {
  if (ctActive) return revealed ? 'plain' : 'chip'
  return 'spoiler'
}
