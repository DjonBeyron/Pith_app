// «Ворота» показа голосового задания сцены в ленте: условия ОКРУЖЕНИЯ, при которых задание не показывается вовсе и лимиты
// (sceneTaskLimits.js: день / раз в 3 слайда / сцена раз в сутки / «позже») НЕ тратятся — сцена просто играет по кругу, как без задания.
// Отдельно от реестра сигналов ранжирования (shared/lib/ranking/signalRegistry.js): тот ставит модули в порядок (compute → value 0..1),
// а здесь «допуск» — да/нет на момент показа, поэтому в реестр это не ложится. Порядок проверок в useSceneTask:
// слайд активен → ВОРОТА (здесь) → микрофон/распознавание (voiceTaskBlockReason) → лимиты (gate.claim).
// Правило добавляется записью в GATES: id (код причины), title/help (для админ-справки), applies(info) — к каким заданиям относится,
// blocked(env) — закрыто ли окружение, text — причина для строки статуса песочницы («пропущено: …»).
// Принудительный показ админа (setForcedSceneTask → gate.forced) обходит ворота — иначе тест на «выключенном» звуке не показать.
export const GATES = [
  {
    id: 'sound_off',
    title: 'Звук ленты выключен',
    help: 'Нет звука = не могу говорить: пока звук ленты выключен (или не было жеста для его включения в этой сессии), голосовые задания сцен («Ответь коту», «Повтори за диктором») не показываются и лимиты не тратят. Звук включили — задание появится на следующем круге или слайде. Текстовое («О чём диалог») звука не требует.',
    applies: info => !!info?.voice,
    blocked: env => !env.soundOn,
    text: 'звук выключен (нет звука — нельзя говорить): включите звук в ленте или нажмите «Показать задание ещё раз» — принудительный показ обходит это правило',
  },
]

// Первое сработавшее правило для задания → { code, text } | null. env: { soundOn: boolean (звук ленты: soundReady), forced?: boolean }
export function taskGateBlock(info, env = {}) {
  if (!info || env.forced) return null
  const g = GATES.find(r => r.applies(info) && r.blocked(env))
  return g ? { code: `gate:${g.id}`, text: g.text } : null
}
