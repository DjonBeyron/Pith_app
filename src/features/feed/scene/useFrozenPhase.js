import { useState } from 'react'

// Фаза панели задания, замороженная на время ухода. После «Готово» / «Спроси позже» состояние задания становится 'closed', а панель ещё
// ~260 мс уезжает вниз (SceneTaskCover): если за это время она перерисуется как «не финал» (вернётся тело с микрофоном/клавиатурой, пропадёт
// вердикт), её высота и содержимое поплывут прямо во время анимации — рваный уход. Поэтому 'closed' не меняет вид: показываем последнюю
// фазу до закрытия. Любая другая фаза применяется сразу. Обновление при рендере (не в эффекте) — без лишнего кадра со старым видом.
export function useFrozenPhase(phase) {
  const [last, setLast] = useState(phase)
  if (phase !== 'closed' && phase !== last) setLast(phase)
  return phase === 'closed' ? last : phase
}
