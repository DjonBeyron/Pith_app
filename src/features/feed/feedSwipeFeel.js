// «Ощущение» свайпа ленты — когда листать, а когда вернуть слайд назад
// (без React и без DOM, чтобы проверять тестами). Используется в FeedSwiper.
//
// Как в TikTok/Instagram и нативных пейджерах iOS/Android: решает скорость
// пальца В МОМЕНТ ОТПУСКАНИЯ (последние ~100мс движения), а не средняя за весь
// жест. Раньше брали среднюю — но палец сначала ложится и чуть замирает, а
// разгоняется только в конце, средняя выходила заниженной, и чтобы
// перелистнуть, требовалось «больше усилия» (жалоба 3.2.1709).
//
// Swiper сам решать не может: он меряет жест часами своих обработчиков, а при
// занятом главном потоке они врут. Здесь — только метки событий (e.timeStamp
// ставит браузер в момент касания).

// Пороги подобраны по отзывам на телефоне: 3.2.1710 (12% / 0.25 / 16px) всё
// ещё требовал «провести пальцем больше, чем в TikTok» — снижены до 8% / 0.15 / 12px
export const FEEL = {
  THRESHOLD_PX: 6, // до стольких пикселей — тап, а не жест (дрожание пальца по лайку)
  DRAG_RATIO: 0.08, // медленное ведение листает, если протащили больше этой доли экрана (~65px)
  FLICK_SPEED: 0.15, // px/мс в момент отпускания (≈150px/с) — это уже флик
  FLICK_MIN_PX: 12, // флик короче — случайный, не листаем
  WINDOW_MS: 100, // за сколько последних мс считаем скорость отпускания
  MIN_SPAN_MS: 30, // короче — скорость по такому отрезку ненадёжна, берём точку раньше
}

// Скорость пальца в момент отпускания, px/мс (+ — палец вниз).
// samples — точки движения [{ t, y }] по порядку, end — точка отпускания.
// Палец замер дольше окна перед отпусканием — скорость 0: решит пройденный путь
export function releaseVelocity(samples, end) {
  let from = null
  for (let k = samples.length - 1; k >= 0; k--) {
    const age = end.t - samples[k].t
    if (age <= FEEL.WINDOW_MS) { from = samples[k]; continue }
    // Опорная точка слишком близко к отпусканию (или её нет вовсе): pointerup
    // приходит в той же точке, что и последнее движение, через пару мс — по
    // такой паре скорость вышла бы 0 и флик потерялся бы. При редких событиях
    // (медленный телефон, нагрузка) берём точку постарше, до двух окон
    if ((!from || end.t - from.t < FEEL.MIN_SPAN_MS) && age <= FEEL.WINDOW_MS * 2) from = samples[k]
    break
  }
  if (!from) return 0
  return (end.y - from.y) / Math.max(1, end.t - from.t)
}

// Вердикт по жесту: dy — общий сдвиг пальца (+ вниз), v — скорость отпускания.
// 'flip' — листать в сторону жеста, 'stay' — вернуть на место (в конце
// дёрнули обратно), null — быстрого движения не было, решает пройденный путь
export function swipeVerdict(dy, v) {
  if (Math.abs(dy) < FEEL.FLICK_MIN_PX) return null
  if (Math.abs(v) < FEEL.FLICK_SPEED) return null
  return Math.sign(v) === Math.sign(dy) ? 'flip' : 'stay'
}

// Итоговый слайд жеста. start — слайд в момент касания, dy — полный путь
// пальца (+ вниз), size — высота слайда. Флик и рывок назад решают сами,
// иначе — путь больше DRAG_RATIO экрана. Палец вверх (dy < 0) — вперёд
export function targetSlide(start, dy, verdict, size) {
  const next = start + (dy < 0 ? 1 : -1)
  if (verdict === 'flip') return next
  if (verdict === 'stay') return start
  return Math.abs(dy) >= FEEL.DRAG_RATIO * size ? next : start
}

// Во что перевести вердикт для Swiper: он решает по доле пройденного пути
// (longSwipesRatio) — 0.01 листает при любом сдвиге, 0.99 — почти никогда
export function ratioFor(verdict) {
  if (verdict === 'flip') return 0.01
  if (verdict === 'stay') return 0.99
  return FEEL.DRAG_RATIO
}
