import LaunchEnergyRow from './LaunchEnergyRow.jsx'

// Карточка запуска, пока сценарий урока едет по сети (~0.7 с).
//
// Раньше здесь была одна строчка «Загрузка урока...», и окно рывком вырастало.
// Потом — пустой каркас, но и он дорисовывался: заголовок и строка про энергию
// появлялись только вместе со сценарием. Теперь показываем всё, что уже знаем:
// название урока пришло из схемы модуля, энергия — из кэша профиля. Ждёт своих
// данных только полоса подготовки, она одна и меняется.
export default function LaunchSkeleton({ title, info }) {
  return (
    <>
      {title
        ? <h2 style={{ margin: 0, color: '#fff', fontSize: 18, fontWeight: 600 }}>{title}</h2>
        /* Название неизвестно (запуск не из схемы модуля) — серая полоска */
        : <div className="launchSkelTitle" />}

      <div style={{ display: 'flex', flexDirection: 'column', gap: 8 }}>
        {/* Жёлоб пустой — ровно как настоящий бар на нуле. Никакой бегущей
            полосы внутри: в первом кадре она стояла на месте и читалась как
            «уже загружено 35%», а через долю секунды обнулялась до реального
            прогресса. Что работа идёт, говорит подпись под ним */}
        <div className="launchSkelTrack" style={{ height: 6, borderRadius: 3, background: '#333' }} />
        {/* Ровно та же строка, что покажет предзагрузчик, вместе с «0%»:
            без процентов они появлялись отдельно и на глаз читались как ещё
            один дорисованный элемент. Ноль здесь честный — не скачано ничего */}
        <span style={{ color: '#888', fontSize: 12 }}>Загрузка урока: 0%</span>
      </div>

      <LaunchEnergyRow info={info} />

      <button
        disabled
        style={{
          padding: '14px 0', borderRadius: 12, border: 'none',
          fontSize: 16, fontWeight: 600, cursor: 'default',
          background: '#333', color: '#666',
        }}
      >Загрузка...</button>
    </>
  )
}
